#!/usr/bin/env bash
# harness-template v0.6.0 — 配布先で見つけた harness の不具合を、ローカルのメモとして書き残す。
#
# ⚠️ **2026-08-08 に大幅に単純化した。** 直前の版(v0.5.0)は次を持っていた:
#
#     1. `gh` で配布先/配布元の可視性を問い合わせ、不一致・判定不能なら拒否する可視性ゲート
#     2. 「欠陥は配布元の着手順へ / 証拠は配布先の .harness/reports/<ID>.md へ」という分割
#     3. --create が無ければ何も書かない下書き既定
#     4. --github で issue を直接開く経路
#
#   この複雑さは**実害から生まれた**: さらに前の版(2026-08-08 より前)が doctor の出力を
#   無条件に添付し、private な配布先の CLAUDE.md・本番障害の詳細・commit SHA を
#   public な issue へ公開した(gigun-dev/claude-code #4)。**その場しのぎの修正として
#   可視性ゲートを足した**のが v0.5.0。ゲートは正しく動いたが、「配布先/配布元の可視性を
#   都度問い合わせて判定する」という仕組みそのものが、この用途(自分用の走り書き)に対して
#   重すぎた。
#
#   ここで立ち返ったのが `docs/principles.md` 規則2「コードでも落第するもの:
#   対象の複雑さを超えた賢さ」。**判定を精密にするのではなく、判定が要らない形にする。**
#   ユーザーの結論: 「起票自体は完全に gitignore かつ private でもいい。最終的に harness へ
#   還元されれば、最初の起票そのものには興味が無い」。
#
#   → **`~/.harness/inbox/` という git の外・$HOME 配下にメモを書くだけにした。**
#     git の管理外なので `git push` という公開経路そのものが存在せず、
#     「可視性を問い合わせて判定する」必要が構造的に消える(ゲートで防ぐのではなく、
#     危険な経路が無い)。欠陥と証拠を分けていたのも可視性が違ったからで、
#     同じ場所(ローカルのみ)に置くなら分ける理由も消える。
#
#   ⚠️ v0.5.0 の冒頭には「inbox のような新しい入れ物は作るな」という注記があった
#     (配布元の着手順が既に ID・完了条件・証拠ゲートを持つ器なので、それを使えという
#     規則6「新機構を足す前に、既存機構で届くか見る」の適用)。**その判断は今も覆していない**
#     —— ここで言う `~/.harness/inbox/` は着手順の代わりではない。採番は一切せず
#     (「あとで上流へ持っていく未処理のメモ」でしかない)、上流へ実際に起票するときは
#     従来どおり配布元の着手順(nd-tasks.sh)を使う。inbox は「起票する前に、その場で
#     git 管理下を汚さず・可視性を気にせず書き殴れる場所」という別の役割で、
#     着手順の代替ではないことに注意。
#
# ⚠️ **doctor の出力(check.sh)は自動添付しない。** 理由は2つ:
#     (1) $HOME 配下でも public に漏れる経路はもう無いが、doctor の生出力は行数が多く
#         「あとで人が上流の着手順へ貼るとき、どこまでが一般化できる欠陥の説明で
#         どこからが配布先固有の事情か」を毎回読み解く負担になる。
#     (2) この用途はあくまで「あとで自分が思い出すためのメモ」。必要な文脈は
#         --note で自分の言葉で書けば足りる。doctor の出力を見ながら書くのはユーザー自身の
#         仕事(このスクリプトの外)であって、スクリプトが自動で埋める仕事ではない。
#   将来また自動添付したくなったら、上の (1)(2) の判断をまず更新すること。
set -u

# ~/.harness/inbox/ — 既定の書き込み先。環境変数で上書きできるのはテスト時の隔離用途。
# ⚠️ `~` はクォート内では展開されない(set -u 前提でも同じ)ので $HOME を使う。
INBOX_DIR="${HARNESS_INBOX_DIR:-$HOME/.harness/inbox}"

usage() {
  cat <<'EOF'
使い方: report.sh --title "<一行要約>" [--note "<補足>"]... [--kind bug|idea]

配布先で見つけた harness の不具合を、$HOME/.harness/inbox/ にローカルのメモとして
1件1ファイルで書き残す。git 管理外・$HOME 配下なので公開の心配は無い。
上流(gigun-dev/claude-code)への実際の起票は、このメモを見ながら人が別途行う。

オプション:
  --title "<要約>"  必須。メモのタイトルになる
  --note "<補足>"   何度でも。期待していた動作 / 実際の動作などを自分の言葉で
  --kind bug|idea   既定 bug
  -h, --help        これ

終了コード:
  0  書いた
  2  使い方の誤り
EOF
}

TITLE=""; KIND="bug"; notes=()
while [ $# -gt 0 ]; do
  case "$1" in
    --title) TITLE="${2:-}"; shift 2 ;;
    --note)  notes+=("${2:-}"); shift 2 ;;
    --kind)  KIND="${2:-bug}"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "不明な引数: $1" >&2; usage >&2; exit 2 ;;
  esac
done
[ -n "$TITLE" ] || { echo "✗ --title は必須です" >&2; usage >&2; exit 2; }

# 起票元リポジトリ名(git 管理下でなければ pwd 名で代用)。
root=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
repo_name=$(basename "$root")

mkdir -p "$INBOX_DIR"

# ファイル名は時刻(UTC秒まで)+ PID で衝突を避ける。ID の採番はしない
# —— 採番は上流の着手順(nd-tasks.sh)の仕事であって、ここでは行わない。
ts=$(date -u +%Y%m%dT%H%M%SZ)
file="$INBOX_DIR/${ts}-$$.md"

# ⚠️ --title / --note はユーザーの自由記述がそのままファイルへ入る。
#    シェルの引数として受け取ったものを `printf '%s'` で書くだけにし、
#    `eval` は使わない・変数展開は必ずダブルクォートで囲む
#    (コマンドインジェクションの経路を作らない)。
{
  printf '# %s\n\n' "$TITLE"
  printf -- '- 起票元リポジトリ: %s\n' "$repo_name"
  printf -- '- 日時: %s\n' "$ts"
  printf -- '- 種別: %s\n' "$KIND"
  printf '\n## 本文(期待していたこと / 実際に起きたこと)\n\n'
  if [ "${#notes[@]}" -gt 0 ]; then
    for n in "${notes[@]}"; do printf -- '- %s\n' "$n"; done
  else
    printf '(--note 未指定。あとで自分でこのファイルに書き足すこと)\n'
  fi
} > "$file"

echo "✓ 書いた: $file"
