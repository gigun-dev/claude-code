#!/usr/bin/env bash
# harness-template v0.8.0 (配布元: gigun-dev/claude-code plugins/harness。配布先の世代確認はこの行を grep)
# SessionStart フック: セッション開始時にプロジェクトの「現在地」を確定的に注入する。
#
# 設計意図(caldav で確立した方式 + 2026-08-05 敵対的検証での補強):
#   - docs/next-directions.md は「冒頭(毎セッション読み込まれる範囲。現在地・着手順)」+
#     「詳細部(`## 方向性カタログ` 以降)」の2部構成。冒頭だけを注入する(全文注入は毎セッション
#     高コストなアンチパターン)。境界は行頭の `<!-- session-head-end` マーカー1行。
#   - マーカーが見つからない場合は全文注入へフォールバックせず、警告だけ注入して止める
#     (fail-closed。旧版はマーカー消失で「全文注入+肥大化警告の同時無効化」が起きた)。
#   - 肥大化(詳細部・冒頭)と鮮度(現在地の日付 vs 最終コミット日)は機械計測する。
#     放置に人間の裁量で気づくのは遅い/不確実。
set -euo pipefail

# フックの cwd はプロジェクトルート。CLAUDE_PROJECT_DIR があればそれを優先(堅牢化)。
# ⚠️ **`docs/` を直書きしない。**install 時に `--docs-dir` の実値が展開される。
#    2026-08-08 の敵対的検証で発覚: ここが `docs/` 固定だったため、
#    `--docs-dir` で導入した瞬間に `[ -r "$doc" ] || exit 0` へ落ちて**フックが無言で死ぬ**。
#    しかも `--docs-dir` は「docs/ が公開サイトなら退避せよ」と導入手順が自ら誘導する経路で、
#    status / tidy / doctor の検知器も同時に空振りする。**原則4 への最も直接的な違反だった。**
doc="${CLAUDE_PROJECT_DIR:-.}/{{DOCS_DIR}}/next-directions.md"
[ -r "$doc" ] || exit 0  # 正典が無い/読めないなら無言で終了(フックはセッションを止めない)

# 閾値は目安。ただし警告を消すために上げるのは禁止(整理が正)。整理後に現況へ
# 「下げ直す」方向のみ調整してよい(上げ方向の調整を許すと検知がラチェット式に死ぬ)。
#
# **2026-08-08: 冒頭の予算を「行」から「文字」へ変えた。**
#   旧 HEAD_MAX_LINES=80 は**どの機構も使っていない単位**だった。実測すると行は言語構成に
#   完全に依存する —— 70行で ≒768 tok(日本語率0%)のファイルと 88行で ≒1,743 tok(30%)が
#   並ぶ。**複数リポジトリへ配る以上、行を予算にすると日本語の正典だけ不当に厳しい。**
#   この stdout を実際に縛っているのは**文字数**: 10,000 文字超で無言に切り詰められ、
#   2KB のプレビューだけが注入される(anthropics/claude-code#70460 / #84021)。
#
# ⚠️ **概算トークンの警告は、ここには置かない**(2026-08-08 に一度入れて、外した)。
#   毎セッションの実費という観点自体は正しいが、**トークン数はベンダー固有** ——
#   文字はテキストそのものの属性だが、トークンは「テキスト × トークナイザ」の属性で、
#   Claude と GPT では語彙が違う。**この配布物は Codex でも動く**ので、Claude 較正の係数を
#   ここへ定数として埋めると他クライアントで黙って嘘をつく。一度は env で上書き可能にして
#   逃げたが、**設定する人が誰もいない投機的な汎用化**だった(消している散文がゼロ)。
#   コストの観点は `/harness:status` と `/harness:doctor` が出す —— あちらはプラグイン側で、
#   人が読む場面でしか走らないので、Claude 既定 + 上書きを持っていてよい。
#   **配布物には、ベンダー非依存で機械的な壁だけを置く。**
#
# ⚠️ **値はここに書かれていない。**install.sh が配布元の `plugins/harness/budgets.sh`
#    (予算の正典)から**展開して**置く —— コンパイルと同じ。だから配布先に実行時依存が
#    生まれず、値の正典は1箇所のままで、**ドリフトが構造的に起きない**(原則7)。
#    直すときは budgets.sh を直して `/harness:doctor` の導入手順を再実行する。
# ⚠️ 詳細部側(CATALOG_MAX_LINES)が行のままなのは意図的 —— **詳細部は注入されない**ので
#    課金されない。ここで守っているのは「人が読み通せる長さ」で、それは実際に行で決まる。
#    **単位は機構ごとに選ぶ。揃えることが目的ではない。**
CATALOG_MAX_LINES={{CATALOG_MAX_LINES}}
UPDATE_BLOCK_MAX={{UPDATE_BLOCK_MAX}}
HEAD_WARN_CHARS={{HEAD_WARN_CHARS}}
HEAD_HARD_CHARS={{HEAD_HARD_CHARS}}

# 展開されずに置かれた場合の fail-loud。**黙って壊れないこと**が一番大事(原則4)——
# 未展開のまま数値比較に入ると "integer expression expected" で異常終了し、
# set -e のせいでセッション開始時に何も注入されないまま静かに終わる。
case "$HEAD_HARD_CHARS" in
  *'{{'*)
    echo '⚠️ このフックは展開されていません(プレースホルダが残っています)。'
    echo '   手でコピーしたか、install が途中で失敗しています。'
    echo '   `/harness:doctor` の導入手順を再実行してください。それまで冒頭は注入されません。'
    exit 0 ;;
esac

# マーカーは行頭アンカーで検出(散文中の "session-head-end" 言及で冒頭が切断される誤爆を防ぐ)。
marker_line=$(grep -n -m1 '^<!-- session-head-end' "$doc" | cut -d: -f1 || true)
if [ -z "$marker_line" ]; then
  echo '⚠️ docs/next-directions.md に session-head-end マーカーが見つかりません(冒頭の注入を停止中)。'
  echo '   現在地・着手順の直後に行頭から `<!-- session-head-end -->` の1行を復元してください。'
  echo '   それまでは docs/next-directions.md を直接読むこと。'
  exit 0
fi

# ============================================================================
# ⚠️ **出力の順序が設計そのもの。警告を先に、冒頭を後に出す。**
#
#   2026-08-08 まで逆だった —— 冒頭を全部出してから末尾に警告を付けていた。
#   だが #70460 は「10,000字を超えると **2KB のプレビューだけ**が注入される」。
#   **つまり切り詰められた瞬間、末尾にある『切り詰められています』の警告が最初に消える。**
#   **切り詰めを知らせる検知器が、切り詰めによって死ぬ。**原則4 の最も純粋な実例で、
#   しかもこの警告を書いた当人(2026-08-08)が一度も超過状態で試していなかった。
#
#   だから: **(1) 全部計測する → (2) 警告を出す → (3) 冒頭を出す。**
#   警告は先頭 2KB に必ず入るので、何が起きているかだけは必ず届く。
#   冒頭の後半が消えるのは避けられないが、**消えたことが分からない**のは避けられる。
#
#   Why not 警告だけ別経路で出す: フックの出力は stdout 1本しかない。順序が唯一の制御。
# ============================================================================

# --- (1) 計測。ここではまだ1バイトも出力しない ------------------------------
# 冒頭の文字数。**ロケールに依存させない**のが要点 ——
# `wc -m` はロケール次第でバイト数を返す(LANG 未設定の macOS が実際にそう)ので使えない。
# 代わりに UTF-8 の構造を直接使う:
#   文字数     = 継続バイト(0x80-0xBF)を落とした残りのバイト数(1文字1バイトに潰れる)
#   (ASCII と非ASCII の内訳は要らない —— ここで見るのは切り詰めだけなので総文字数で足りる)
# ⚠️ 測っているのは冒頭だけだが、切り詰めの対象は**この stdout 全体**(見出し行 + 警告文も含む)。
#    見出し行は約 130 字、警告文は出ても数百字なので、8,000 / 10,000 の 2,000 字の余裕で吸収する
#    —— 余裕はそのためにある。ここを縮めるなら見出しと警告も計測に含めること。
head_chars=$(sed -n "1,$((marker_line - 1))p" "$doc" | LC_ALL=C tr -d '\200-\277' | wc -c | tr -d ' ')

# 詳細部(マーカー以降)の行数と更新ブロック数。**数えるだけで印字しない。**
# 更新ブロックのパターンは寛容に取る(太字省略・スラッシュ日付も数える)。教える正書式は
# 太字だが、書式が少しズレただけで計測が静かに死ぬ設計にしない(敵対的検証の指摘)。
catalog_stats=$(awk -v marker="$marker_line" '
  NR <= marker { next }
  { catalog++; if ($0 ~ /^[[:space:]]*> (\*\*)?20[0-9][0-9][-\/].*更新(:|：)/) updates++ }
  END { print catalog+0, updates+0 }
' "$doc")
catalog_lines=${catalog_stats%% *}
update_blocks=${catalog_stats##* }

# 鮮度検査: 冒頭の「## 現在地(YYYY-MM-DD)」の日付より新しいコミットがあれば、更新漏れの可能性を警告。
# 日付粒度の比較なので当日中の連続作業では鳴らない(緩い検査。強制機構ではなく検知器)。
#
# ⚠️ **この検査は2回、書式のズレで黙って死んでいる。**
#   1回目(caldav 第5版): 全角「現在地（…）」が読めなかった → 括弧を全角/半角の両対応に。
#   2回目(2026-08-08): `## 現在地(2026-08-06・第2版)` が読めなかった。日付の**直後に閉じ括弧**を
#     要求していたため、版数などの接尾辞が付くと 0 件になる。同じ死に方の再発。
#
# **2回とも「教える書式を厳密に写した正規表現」が原因。**そこで今回は写すのをやめた ——
# **見出し行を先に特定し、その行から最初の日付を拾う**。括弧の有無・全半角・接尾辞の順序に
# 一切依存しない。原則「計測は寛容に、教える書式は厳密に」の、寛容側を本気で取る形。
# Why not 全文から最初の日付を拾う: 冒頭の本文に日付(更新ブロックなど)があると、それを
# 現在地の日付と誤認する。見出し行への限定はここだけは外せない。
head_line=$(sed -n "1,${marker_line}p" "$doc" | grep -m1 -E '^#+[[:space:]]*現在地' || true)
head_date=$(printf '%s' "$head_line" | grep -oE '20[0-9]{2}-[0-9]{2}-[0-9]{2}' | head -1 || true)

last_commit=""
if [ -n "$head_date" ] && command -v git >/dev/null 2>&1; then
  last_commit=$(git -C "${CLAUDE_PROJECT_DIR:-.}" log -1 --format=%cs 2>/dev/null || true)
fi

# --- (2) 警告を先に出す。**ここが 2KB のプレビューに必ず入る部分** ------------
# ⚠️ hardchars は「もう切れている」——「これから気をつけて」ではない。文言を弱めないこと。
if [ "$head_chars" -gt "$HEAD_HARD_CHARS" ]; then
  printf '✗ 冒頭が %d 字あります(上限 %d 字)—— **この出力はいま無言で切り詰められており、先頭 2KB しか届いていません**(anthropics/claude-code#70460)。整理するまで冒頭の後半は読まれません。\n\n' "$head_chars" "$HEAD_HARD_CHARS"
elif [ "$head_chars" -gt "$HEAD_WARN_CHARS" ]; then
  printf '⚠️ 冒頭が %d 字あります(目安 %d 字・切り詰めは %d 字)。現在地・着手順は要約し、積み重なった経緯の追記は詳細部か git 履歴へ。\n\n' "$head_chars" "$HEAD_WARN_CHARS" "$HEAD_HARD_CHARS"
fi

if [ "$catalog_lines" -gt "$CATALOG_MAX_LINES" ] || [ "$update_blocks" -gt "$UPDATE_BLOCK_MAX" ]; then
  printf '⚠️ next-directions.md の詳細部が肥大化しています(%d 行 / 更新ブロック %d 個、閾値 %d 行 / %d 個)。\n' "$catalog_lines" "$update_blocks" "$CATALOG_MAX_LINES" "$UPDATE_BLOCK_MAX"
  printf '   整理(次版)を実施してください — 積み重なった「> 日付 更新:」を本文に反映し、冒頭を最新の現在地に更新する。\n'
  printf '   ⚠️ 閾値を上げて警告を消すのは禁止。整理後に現況へ下げ直すのは可。\n\n'
fi

# **見出しはあるのに日付が取れない = 検知器が死んでいる。**黙って通さない(原則4)。
# ここを無警告で素通りさせたのが、上の2回の事故が長く見つからなかった理由そのもの。
if [ -z "$head_line" ]; then
  printf '⚠️ 冒頭に `## 現在地` の見出しがありません(鮮度検査が無効化されています)。\n\n'
elif [ -z "$head_date" ]; then
  printf '⚠️ 現在地の見出しから日付が読めません(鮮度検査が無効化されています)。見出しを `## 現在地(YYYY-MM-DD)` の形にしてください。\n   いまの見出し: %s\n\n' "$head_line"
elif [ -n "$last_commit" ] && [ "$last_commit" \> "$head_date" ]; then
  printf '⚠️ 現在地の日付(%s)より新しいコミット(%s)があります — 冒頭の更新漏れの可能性。作業前に現在地を最新化してください。\n\n' "$head_date" "$last_commit"
fi

# --- (3) 冒頭を出す。**切り詰められるならここが消える** ----------------------
# Why not awk: 印字だけなら sed で足りる。awk が「印字と計測」を兼ねていたのが、
# 警告を末尾へ追いやっていた構造的な原因だった(END でしか計測結果を使えないので)。
# **計測と印字を分けた結果、順序を自由に決められるようになった。**
# 見出しも実際のパスを出す(`docs/` 直書きだと --docs-dir のとき見出しだけ嘘になる)。
printf '=== %s の冒頭(毎セッション読み込まれる範囲。現在地・着手順)。詳細部は該当節をそのとき読む。更新は「> **YYYY-MM-DD 更新:**」を追記していく・計画は消さない ===\n' "{{DOCS_DIR}}/next-directions.md"
sed -n "1,$((marker_line - 1))p" "$doc"
