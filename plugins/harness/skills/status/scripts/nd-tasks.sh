# US 区切りの1レコードを書く。IFS の先頭文字で "$*" が連結される性質を使う。
emit_rec() { local IFS="$US"; printf '%s\n' "$*" >> "$RECS"; }

# そのリポジトリのフックが「頭注入型」か(= session-head-end を読むか)。
#
# マーカー欠落の意味は、フックの配線で3通りに分かれる:
#   (a) 頭注入型のフックがある + マーカー無し → **注入が fail-closed で停止している**(違反)
#   (b) pointer 型フック(この repo)         → そもそも頭を注入しないので停止ではない(警告)
#   (c) フックが無い(ハーネス未導入)         → 同上(警告。直すのは /harness:doctor)
# 一律に違反にすると (b)(c) で毎回鳴り、検知器が信用されなくなる —— このリポジトリは
# 「検知器が黙って死ぬ」と同じくらい「鳴りすぎて無視される」を嫌う。実測では
# tdr-concierge は (c) だった(フック自体が無い。「停止中」ではなく未導入)。
head_injection_mode() {
  local root=$1
  grep -rqs 'session-head-end' "$root/.claude/hooks" 2>/dev/null && echo 1 || echo 0
}

# ファイルパスから (リポジトリルート, コンポーネント名) を決める。
#   <root>/docs/next-directions.md        → comp="" (単一プロダクト型)
#   <root>/docs/<comp>/next-directions.md → comp=<comp>
root_of() {
  local d; d=$(cd "$(dirname "$1")" && pwd)
  case "$d" in
    */docs)   printf '%s\n' "${d%/docs}" ;;
    */docs/*) printf '%s\n' "${d%/docs/*}" ;;
    *)        printf '%s\n' "$d" ;;   # docs 配下でない明示指定(書式検証用の一時ファイルなど)
  esac
}
comp_of() {
  local d; d=$(cd "$(dirname "$1")" && pwd)
  case "$d" in
    */docs) printf '%s\n' "" ;;
    *)      basename "$d" ;;
  esac
}

# 1ファイルを走査して F/I/E レコードを積む。
scan_file() {
  local f=$1 root comp repo marker head_chars head_tokens has_marker inject
  root=$(root_of "$f"); comp=$(comp_of "$f"); repo=$(basename "$root")
  inject=$(head_injection_mode "$root")

  # 頭(SessionStart が注入する範囲)の文字数とトークン数。フックは marker 行の**手前まで**を
  # 出すので、計測もそこに揃える(marker 行自身と、フックが足す見出し行は含めない)。
  # 行頭アンカーで探すのはフックと同じ理由 —— 散文中で session-head-end に言及しただけで
  # 頭が切れる誤爆を防ぐ。
  marker=$(grep -n -m1 '^<!-- session-head-end' "$f" | cut -d: -f1 || true)
  if [ -n "$marker" ]; then
    has_marker=1
    measure "$(sed -n "1,$((marker - 1))p" "$f")"
  else
    has_marker=0
    measure "$(cat "$f")"   # 頭が定義できない。参考値として全文サイズを出す
  fi
  head_chars=$MEAS_CHARS; head_tokens=$MEAS_TOKENS
  emit_rec F "$repo" "$comp" "$f" "$head_chars" "$has_marker" "$inject" "$root" "$head_tokens"

  if [ "$has_marker" -eq 0 ]; then
    if [ "$inject" -eq 1 ]; then
      emit_rec E "$repo" "$comp" "$f" no-marker 0 V \
        "session-head-end マーカーが無い —— このリポジトリのフックは冒頭注入型(冒頭 = 毎セッション読み込まれる範囲)なので、**注入が fail-closed で停止している**(誰も気づかないまま止まる)。現在地・着手順の直後に行頭から <!-- session-head-end --> を復元すること"
    else
      emit_rec E "$repo" "$comp" "$f" no-marker 0 W \
        "session-head-end マーカーが無い(このリポジトリに冒頭注入型のフックが無い = pointer 型かハーネス未導入。注入が止まっているわけではないが、冒頭/詳細部の境界が無いので読み手は全文を読むことになる。導入は /harness:doctor)"
    fi
  else
    # #70460 / #84021: SessionStart の stdout は **10,000 文字**超で無言に切り詰められ、
    # 2KB のプレビューだけが注入される。バイトでも行でもなく**文字**で効く制限。
    #
    # ⚠️ **2026-08-08 追加。この3件の警告は元々「頭は毎セッション SessionStart の stdout を
    #    通って注入される」ことを暗黙の前提にしていたが、その前提は**頭注入型のフックに
    #    しか成り立たない**。pointer 型(このリポジトリ自身がそう。docs/harness/
    #    next-directions.md の「doctor の指摘のうち却下するもの」に同じ却下記録がある)では
    #    フックが出すのは「=== harness を開発するなら: 現在地は … ===」という**1行の
    #    ポインタだけ**で、頭そのものは stdout を通らない。したがって:
    #      - head-truncated / head-large が名指しする「10,000字で無言に切り詰められる」壁は、
    #        stdout を通らない頭には**そもそも適用されない** —— 存在しない機構を根拠に
    #        警告を出すと、鳴った側のリポジトリで確かめても再現せず「この検知器は当たらない」
    #        という不信を生み、他の正しい警告まで無視される方向に倒れる(このリポジトリが
    #        「検知器が黙って死ぬ」と同じくらい嫌う壊れ方)。
    #      - head-costly の「毎セッション注入されるのでコストになる」も同じ理由で偽。
    #        ただし**頭が肥大していること自体は pointer 型でも事実として残る**
    #        (ポインタを辿って読みに行けば、そこで文字/トークンぶんのコストを払う)。
    #        だから head-costly は消さず、理由の文面だけを実態に合わせる(重大度は W のまま)。
    #    判定は新しい検出機構を足さず、上の has_marker=0 の分岐で既に使っている $inject
    #    (= head_injection_mode() の結果)をそのまま再利用する(docs/principles.md 規則6
    #    「新機構を足す前に、既存機構で届くか見る」)。
    #
    #    **$inject=1(冒頭注入型)のときは、この 2026-08-08 の変更で判定も文面も動かしていない**
    #    —— 既存の配布先(実際に冒頭注入型で運用されているリポジトリ)へ与える内容は変えない。
    #    ⚠️ 2026-08-10 に**語彙だけ**直した(「頭」→「冒頭」/「棚卸し」→「整理」/「カタログ部」→
    #    「詳細部」)。条件も数値も分岐も動かしていない、純粋な言い換え —— 配布先のエージェントは
    #    読んだ文書の言葉づかいをそのまま真似るので、ここだけ独自語彙が残ると各リポジトリへ伝播する。
    if [ "$inject" -eq 1 ]; then
      if [ "$head_chars" -gt "$HEAD_HARD_CHARS" ]; then
        emit_rec E "$repo" "$comp" "$f" head-truncated 0 W \
          "冒頭が ${head_chars}字(> ${HEAD_HARD_CHARS}字)—— SessionStart の stdout は 10,000字超で**無言に切り詰められ 2KB のプレビューだけが注入される**(anthropics/claude-code#70460・#84021)。いま実際に切れている。整理して冒頭を縮めること"
      elif [ "$head_chars" -gt "$HEAD_WARN_CHARS" ]; then
        emit_rec E "$repo" "$comp" "$f" head-large 0 W \
          "冒頭が ${head_chars}字(目安 ${HEAD_WARN_CHARS}字)—— 10,000字を超えると SessionStart の stdout が無言に切り詰められる(#70460)。余裕が ${HEAD_HARD_CHARS}字まで"
      fi
    fi
    # トークンは切り詰めとは別の機構。$inject の値にかかわらず「頭が大きい」という事実
    # そのものは変わらないので、head-costly は頭注入型・pointer 型のどちらでも出す
    # (⚠️ 消えるのは文面の理由だけで、鳴る/鳴らないの判定は変えない —— この変更で
    # 警告の**件数**を減らすと、budgets.sh の「⚠️ 閾値を上げて警告を消すのは禁止」に反する
    # 「棚卸し前に検査側を緩めて警告を消した」ことになってしまう)。
    if [ "$head_tokens" -gt "$HEAD_WARN_TOKENS" ]; then
      if [ "$inject" -eq 1 ]; then
        # 冒頭注入型: 既存文面のまま(毎セッションの実費として鳴らす)。2026-08-08 の分岐追加では
        # 動かしておらず、2026-08-10 の語彙の言い換え(上のコメント参照)だけが入っている。
        emit_rec E "$repo" "$comp" "$f" head-costly 0 W \
          "冒頭が ≒${head_tokens} tok(予算 ${HEAD_WARN_TOKENS} tok)—— 切り詰めには余裕があるが、**毎セッション注入されるので全セッションのコストになる**。整理するか --archive で降ろすこと"
      else
        # pointer 型 / ハーネス未導入: 「毎セッション payer」ではなく「ポインタを辿って
        # 読みに行ったときに1回払う」コストとして書き直す。頭が大きいこと自体は消えて
        # いない問題として残すので、重大度は同じ W のまま(V へ格上げしない)。
        #
        # ⚠️ **この字数/トークンの予算自体、pointer 方式では裏付ける機構が無い。**
        #    切り詰め(10,000字)も毎セッション注入もここでは起きないので、"予算 ${HEAD_WARN_TOKENS} tok"
        #    という数字は「守るべき壁」ではなく単なる目安に格下げされている。pointer 型で
        #    本来守りたいのは「(ポインタを辿って)再開するエージェントが読み通せるか」で、
        #    それは stdout を通らない文書(カタログ部・log.md。budgets.sh 参照)と同じ性質
        #    —— **本来の単位は行のはず。** ただし今この場で行の予算へ切り替えると、
        #    「棚卸し(H-5: docs/harness/next-directions.md)より前に検査側を緩めて
        #    警告を静かに消す」ことになりかねない(budgets.sh の「⚠️ 閾値を上げて警告を
        #    消すのは禁止」の精神に反する)。だから**今は文字/トークンのまま出し続け**、
        #    行へ移す判断は H-5 の棚卸しが終わってから現況に合わせて下げ直す
        #    (docs/harness/next-directions.md の「H-22 と同型の判断」を参照)。
        # ⚠️ 上の判断を**警告文には書かない。**初版は「本来の単位は行のはずだが、棚卸し前に
        #    切り替えると警告を消すことになるので H-5 の後に決める」まで警告へ入れて **278字**
        #    になっていた(従来は約100字)。それは**将来の設計判断の説明**であって、いま警告を
        #    読んだ人の行動は変えない —— 規則2b「その一文はエージェントの行動を変えるか」。
        #    判断はこのコメントに置き、警告は「何をすればよいか」だけに絞る。
        emit_rec E "$repo" "$comp" "$f" head-costly 0 W \
          "冒頭が ≒${head_tokens} tok(目安 ${HEAD_WARN_TOKENS} tok)—— このフックは pointer 型なので**毎セッション注入されるわけではない**が、ポインタを辿って読むたびに払う。整理するか --archive で降ろすこと"
      fi
    fi
  fi

  awk -v repo="$repo" -v comp="$comp" -v file="$f" -f "$PARSER" "$f" >> "$RECS"
}

# 1リポジトリ配下の正典を列挙する。単一プロダクト型と複数コンポーネント型の両対応
# (tidy.sh の探索と同じ形。片方だけ見ると、この repo のような marketplace 型を取りこぼす)。
nds_of_repo() {
  local root=$1 f
  [ -f "$root/docs/next-directions.md" ] && printf '%s\n' "$root/docs/next-directions.md"
  for f in "$root"/docs/*/next-directions.md; do
    [ -f "$f" ] && printf '%s\n' "$f"
  done
  return 0
}

# =============================================================================
# 書き込み操作の実行(--add / --done / --note / --rewrite / --archive)
# =============================================================================
# 引数の検証は上の「書き込み操作の引数検証」で済ませてある。ここは「引数は正しい」前提で、
# 対象ファイルを1本に決め、エディタ(awk)に新しい全文を作らせ、atomic に置き換えるだけ。
#
# **読み取り経路には一切入らない。** 下の収集ループ(scan_file / RECS)まで落ちてこない
# ように、この if の中で必ず exit する —— 書き込みの後に一覧を出すと、出力が
# 「何をしたか」と「いま何があるか」で混ざって、どちらの話か読めなくなる。
if [ -n "$OP" ]; then
  # --- 対象ファイルを1本に決める(fail-closed) -------------------------------
  # **複数候補があるときは推測しない。** この repo のように docs/harness/ と docs/ios-skills/
  # の2本を持つ構成で「たぶん harness の方だろう」と決め打つと、**別のコンポーネントの正典を
  # 書き換える**という取り返しのつかない事故になる。読み取り(--all)と違い、書き込みでは
  # 曖昧さを許さない。
  TARGET=""
  if [ ${#EXPLICIT[@]} -gt 1 ]; then
    echo "✗ 書き込み操作の対象は1ファイルだけ(${#EXPLICIT[@]} 件が指定された)。" >&2
    echo "  1本ずつ実行すること。" >&2
    exit 2
  elif [ ${#EXPLICIT[@]} -eq 1 ]; then
    TARGET="${EXPLICIT[0]}"
    [ -f "$TARGET" ] || { echo "✗ ファイルが無い: $TARGET" >&2; exit 2; }
  else
    wbase=$(cd "${CLAUDE_PROJECT_DIR:-.}" && pwd)
    ncand=0
    # 1行1ファイルで受ける($(...) を直接 for に食わせると空白入りパスが割れる。
    # 割れたときの症状が「静かに1件も見つからない」なので、読み取り側と同じ形にする)。
    while IFS= read -r f; do
      [ -n "$f" ] || continue
      ncand=$((ncand + 1)); TARGET="$f"; cand_list="${cand_list:-}  $f"$'\n'
    done <<EOF
$(nds_of_repo "$wbase")
EOF
    if [ "$ncand" -eq 0 ]; then
      echo "✗ $wbase に docs/next-directions.md も docs/*/next-directions.md も無い。" >&2
      echo "  ハーネス未導入なら /harness:doctor で導入できる。" >&2
      exit 2
    elif [ "$ncand" -gt 1 ]; then
      echo "✗ next-directions.md が $ncand 本ある —— どれに書くかを推測しない(別コンポーネントの" >&2
      echo "  正典を書き換える事故を防ぐため)。パスを引数で明示すること:" >&2
      printf '%s' "$cand_list" >&2
      exit 2
    fi
  fi
  TARGET="$(cd "$(dirname "$TARGET")" && pwd)/$(basename "$TARGET")"

  # --- 排他ロックを取る(ここから read-modify-write の終わりまでを包む) --------
  # **対象ファイルが1本に決まった直後、構造を読む(layout parse)より前**に取る。
  # 「読む → 全文を組み立てる → mv」全体を1つの排他区間にしないと、複数プロセスが
  # 同じ古い内容を読んで別々の +1 を作り、後勝ちの mv だけが残る(実測した lost update)。
  # 解放は EXIT/INT/TERM/PIPE の cleanup trap に任せる —— ここでは待つだけでよい
  # (このブロックの以降のあらゆる exit 経路は、その trap を必ず経由して抜ける)。
  LOCKDIR="$(dirname "$TARGET")/.$(basename "$TARGET").lock"
  if ! acquire_lock; then
    echo "✗ ロックが取れない($LOCKDIR)。${LOCK_WAIT_TOTAL}秒待っても他プロセスが解放しなかった。" >&2
    echo "  **何も書いていない。**別の書き込み操作(--add / --done / --note / --rewrite / --archive)が" >&2
    echo "  同時に走っている可能性がある。しばらく待ってから再実行すること。" >&2
    echo "  それでも解消しないなら、持ち主が異常終了した可能性がある —— $LOCKDIR/owner の" >&2
    echo "  PID が実在するか確認し、実在しなければ手動で rm -rf しても安全(fail-closed の後始末)。" >&2
    exit 3
  fi

  # --- エディタ(awk) ---------------------------------------------------------
  # ⚠️ 読み取り側のパーサと同じ理由で、プログラムは一時ファイルへ書いて `awk -f` で渡す。
  #    `PROG=$(cat <<'AWK' …)` の形にすると、**bash 3.2(macOS 標準)が $( ) の中で
  #    引用符付きヒアドキュメントの中身まで走査し、本文のバッククォートをコマンド置換の
  #    開始と誤認して構文エラーになる**。ID をバッククォート囲みで扱う以上、必ず踏む。
  #
  # 入出力の契約:
  #   stdout            書き換えた後の**全文**(呼び出し側が atomic に置き換える)
  #   report ファイル   "<SEV>\t<メッセージ>" の行。SEV は E=違反 / W=警告 / I=情報 /
  #                     M=移動の内訳 / N=採番した ID / C=件数
  #   終了コード        0=変更あり(stdout が有効) / 10=変更不要(冪等) / 3=状態エラー
  #
  # **利用者が渡す文字列は -v ではなく環境変数(ENVIRON)で受ける。** awk の -v は値の中の
  # バックスラッシュをエスケープシーケンスとして解釈するので、`C:\path` や `\n` を含む
  # 概要・証拠が**静かに壊れる**。ENVIRON にはその変換が無い。
  EDITOR="$tmp/edit.awk"
  cat > "$EDITOR" <<'AWK'
# --- 小道具 -----------------------------------------------------------------
# ⚠️ **このエディタは書式を解釈しない。**「どの行が何であるか」(節の範囲・項目の ID と
#    行範囲・字下げ・証拠の有無・採番の材料)は**すべてパーサ(parser.awk)が決め**、
#    ここへは layout ファイル経由で**行番号として**渡ってくる。
#    したがってこのプログラムに `^## 着手順` / `^- \[` / バッククォート囲みの ID /
#    `→` / `>` といった**書式の正規表現は1本も無い**。触ってよい行を行番号で受け取り、
#    その周りに行を足す・状態文字を1文字書き換える・行を消す —— それだけをする。
#    (2026-08-08 / H-19。それまでは同じ書式規則がここにも実装されていて、実際に
#     読み側と答えが割れていた。経緯はパーサ側「layout モード」のコメントが正。)
# 残っているのはこれだけ —— **空行かどうか**は書式の解釈ではなく、行を平行移動するときの
# 素の判定(字下げの計算はパーサが出す imind に寄せたので ind_of() は要らなくなった)。
function blank(s) { return (s ~ /^[ \t]*$/) }
function sp(k,   s) { s = ""; while (length(s) < k) s = s " "; return s }
# **利用者が渡した値**の行頭空白を落とす(ファイルの行ではない)。sanitize_value が
# 畳んだ 6 桁の字下げを剥がし、項目の実際の字下げへ揃え直すために要る。
# ⚠️ これは「書式の解釈」ではない —— 入力文字列の正規化であって、正典のどの行が
#    何であるかの判断は1つも含まない(その判断はパーサだけが持つ、という線は保たれている)。
function lstrip(s) { sub(/^[ \t]+/, "", s); return s }
function say(sev, msg) { print sev "\t" msg >> report }
# **何も書かずに落ちる**のがこの関数の全て。呼び出し側は exit 3 を見て stdout を捨てる。
function die(msg) { say("E", msg); exit 3 }
# 「i 行目の直後に足す行」を積む。削除(del)と併せて、出力は emit() が1回で組み立てる ——
# 行番号を動かしながら書き換えると、後続の位置がずれて**別の項目を壊す**。
# 引数名は pos。**at にしない** —— layout から受け取るグローバルの `at`(--add の挿入位置)と
# 同名になり、awk では仮引数が黙って外側を隠す。動作は変わらないが読み手が二度見る。
function add_ins(pos, text) { insn[pos]++; ins[pos, insn[pos]] = text }

# --- 構造の受け取り(パーサの layout 出力) ------------------------------------
# **ここが locate_sections() + collect_items() + scan_all_ids() + dominant_prefix() の
# 代わり。**それら4つは書式の正規表現を持っており、読み側の同じ規則の**2つ目の実装**
# だった。実際に割れていた(マーカーより下の2つ目の `## 着手順` を、読み側は読み、
# 書き側は読まない)。いまは1行も解釈せず、パーサが出した行番号を配列へ移すだけ。
#
# 受け取る値(詳細はパーサ側「layout モード」のコメント):
#   ss / se        「着手順」節の見出し行 / 終端(**その行は節の外**という排他境界)
#   at / atprose    節の中の最後の非空行 / それが散文か(--add の前に空行が要るか)
#   ds / de         「完了記録」節の見出し行 / 終端(0 = 節が無い)
#   dat / dhas      完了記録の追記位置 / 既存エントリ(`- `)があるか
#   mk              session-head-end マーカー行(0 = 無い)
#   pfx / maxn      採番の接頭辞 / ファイル全体でのその接頭辞の最大番号
#   istart[] iend[] iid[] istat[] isum[] imind[] iaind[] ihas_evi[] ipara[] iedate[]
#   iscol[]         項目行のうち `- [x] `ID`` までの桁数(--rewrite が保つ範囲の右端)
#   ikinds[]        継続行の種別表 "<行番号>:<種別> …"(--rewrite だけが読む)
#   arch[id]        完了記録に降ろし済みの ID
function read_layout(   line, f, k, nrec) {
  nrec = 0
  # getline < file は失敗時に -1 を返す(> 0 のときだけループが回る)。
  # 読めなかったのか空だったのかを区別する必要は無い —— どちらも「構造が取れていない」で、
  # **何も書かずに落ちる**のが正しい(fail-closed)。
  while ((getline line < layoutfile) > 0) {
    nrec++
    split(line, f, US)
    if (f[1] == "L") lv[f[2]] = f[3]
    else if (f[1] == "A") arch[f[2]] = 1
    else if (f[1] == "C") ikinds[f[2] + 0] = f[3]
    else if (f[1] == "T") {
      k = f[2] + 0; if (k > ni) ni = k
      iid[k] = f[3]; istat[k] = f[4]; istart[k] = f[5] + 0; iend[k] = f[6] + 0
      imind[k] = f[7] + 0; iaind[k] = f[8] + 0; ihas_evi[k] = f[9] + 0
      ipara[k] = f[10] + 0; iedate[k] = f[11]; iscol[k] = f[12] + 0; isum[k] = f[13]
    }
  }
  close(layoutfile)
  if (nrec == 0)
    die("内部エラー: 構造レコードが1本も読めなかった(" layoutfile ")。**何も書いていない。**")
  ss = lv["SS"] + 0; se = lv["SE"] + 0
  at = lv["AT"] + 0; atprose = lv["ATP"] + 0
  ds = lv["DS"] + 0; de = lv["DE"] + 0
  dat = lv["DAT"] + 0; dhas = lv["DHAS"] + 0
  mk = lv["MK"] + 0
  pfx = lv["PFX"]; maxn = lv["MAX"] + 0
  # **パーサとエディタは同じファイルを別々に読む。**同じ内容を見たことをここで確かめる ——
  # 行数が違うなら、その間にファイルが書き換わったか、どちらかの読み込みが壊れている。
  # 行番号だけを頼りに書く以上、ここがずれたら**別の行を壊す**ので絶対に進めない。
  if (lv["NL"] + 0 != n)
    die("内部エラー: 構造の解析(" (lv["NL"] + 0) " 行)と本文(" n " 行)の行数が食い違う —— 実行中にファイルが書き換わった可能性がある。**何も書いていない。** もう一度実行すること。")
  if (ss == 0)
    die("`## 着手順` 節が無い —— 書き込む場所が決められないので**何も書いていない**。旧書式のままなら `## 着手順(次にやること)` 見出しを作り、`- [ ] `ID-1` 概要` 形式へ移行すること(/harness:doctor が配る雛形が正)。")
}

# 項目を ID で引く。**ここは「照合」ではなく「表の引き当て」。**行から ID を切り出す
# 仕事はパーサ側にあり、この配列にはもう切り出し済みの ID が入っている。
function find_item(qid,   k) {
  for (k = 1; k <= ni; k++) if (iid[k] == qid) return k
  return 0
}

# 未知の ID。「そんな ID は無い」で終わらせず、**次の一手**を出す ——
# 完了記録に在るなら打ち間違いではないし、在る ID を並べれば探す手間が消える。
# 「完了記録に在るか」はパーサが出した A レコード(arch[])で判る。
# ⚠️ 旧実装はここで `substr(L[i],1,4) == "- ~~"` と本文を舐めていた —— **完了記録の
#    書式の3つ目の実装**だった。書式を知っているのはパーサだけ、という線をここでも守る。
function unknown_id(   k, list) {
  if (id in arch)
    die("`" id "` は「着手順」に無い —— 「完了記録」に在る(既に --archive 済み)。**何も書いていない。** 閉じ直す必要は無い。")
  list = ""
  for (k = 1; k <= ni; k++) list = list (list == "" ? "" : ", ") "`" iid[k] "`"
  die("`" id "` という ID の項目が「着手順」に無い。**何も書いていない。** いま在るのは: " (list == "" ? "(0件)" : list))
}

# --- 操作: --add ------------------------------------------------------------
# 採番(接頭辞 pfx と最大番号 maxn)はパーサが**ファイル全体**(着手順 + 完了記録 +
# カタログ部 + 散文中の参照)を走査して出したもの。着手順だけを見ると、--archive で
# 完了記録へ降ろした ID を再利用してしまい、log.md やコミットメッセージからの参照
# (「`H-1` の件」)が**別物を指す**ようになる。欠番は安全だが再利用は嘘を作る。
function do_add(   nid) {
  if (pfx == "")
    die("採番の接頭辞が決められない —— 「着手順」にも「完了記録」にも `H-1` 形式の項目が1本も無い。**何も書いていない。** 最初の1件だけは手で書いて接頭辞を決めること(プロジェクトの略号にする。例: caldav なら `CD-1`)。")
  nid = pfx "-" (maxn + 1)
  # 挿入位置 = 節の中の最後の非空行(at)の直後。項目があればその末尾、無ければ導入散文の直後。
  # 「末尾へ足す」のは着手順が**優先順ではなく追加順**だから(順序を変えたいときは人が動かす)。
  # atprose = その行が散文(箇条書きでも継続行でもない)かどうか。**この判定もパーサ側**。
  if (at == 0) { at = ss; add_ins(at, "") }
  else if (atprose) add_ins(at, "")               # 直上が散文なら空行を1本
  add_ins(at, "- [ ] `" nid "` " ENVIRON["ND_SUMMARY"])
  add_ins(at, sp(6) "→ 完了条件: " ENVIRON["ND_CRITERIA"])
  say("N", nid)
  say("I", "採番 `" nid "` = 接頭辞 " pfx " の最大値 " maxn " + 1(**ファイル全体**を走査した。着手順だけを見るとアーカイブ済み ID を再利用する)")
  changed = 1
}

# --- 操作: --done -----------------------------------------------------------
function do_done(   k, ind) {
  k = find_item(id)
  if (k == 0) unknown_id()
  # 冪等。2回目は**エラーにしない** —— 再実行が安全でないスクリプトは、失敗したときに
  # 「もう一度叩いてよいか」を人が判断しなければならず、そこで手作業に戻る。
  if (istat[k] == "x" && ihas_evi[k]) {
    say("I", "`" id "` は既に完了(`[x]` + 証拠行あり)。何もしていない。")
    changed = 0
    return
  }
  # 証拠行の字下げは既存の「→」行に揃える。無ければ継続行の最小字下げ、それも無ければ 6
  # (`- [x] ` の幅。読み側は字下げ幅を問わないが、揃っていないと人が読めない)。
  ind = (iaind[k] > 0 ? iaind[k] : (imind[k] > 0 ? imind[k] : 6))
  add_ins(ipara[k], sp(ind) "→ " ENVIRON["ND_EVIDENCE"])
  if (istat[k] == "x")
    say("W", "`" id "` は既に `[x]` だったが証拠行が無かった —— 証拠行だけを足した(--lint の no-evidence 違反はこれで解消する)。")
  else {
    L[istart[k]] = substr(L[istart[k]], 1, 3) "x" substr(L[istart[k]], 5)
    say("I", "`" id "` を `[x]` にし、証拠行を項目の最後に足した。")
  }
  changed = 1
}

# --- 操作: --note -----------------------------------------------------------
function do_note(   k, ln, j, nind) {
  k = find_item(id)
  if (k == 0) unknown_id()
  # 字下げは 2 桁。list item の内容カラムが 2 桁なので、そこに `>` を置くと
  # **項目の中の引用ブロック**として描画される。6 桁にすると相対 4 桁 =
  # インデントコードブロック扱いになり、`> **… 更新:**` がそのまま等幅で出てしまう。
  # かつ 2 桁は直前の「→」行の字下げ(通常 6)以下なので、読み側のパーサに
  # **証拠行の折り返し**と誤読されない(折り返し判定は「直前の → 行より深い」)。
  # 「→」行が 1 桁という異常な字下げのときだけ、それに合わせて更に浅くする。
  nind = 2
  if (iaind[k] > 0 && iaind[k] < 2) nind = iaind[k]
  ln = sp(nind) "> **" today " 更新:** " ENVIRON["ND_NOTE"]
  # 二重実行での重複を防ぐ。積層(append)が本来の意味なので**内容が違えば何本でも積む**が、
  # 完全一致は「同じコマンドをもう一度叩いた」以外にありえないので黙って落とす。
  for (j = istart[k]; j <= iend[k]; j++) if (L[j] == ln) {
    say("I", "同じ内容の更新行が既にある(" j " 行目)。足さなかった。")
    changed = 0
    return
  }
  add_ins(iend[k], ln)
  say("I", "`" id "` の末尾に `> **" today " 更新:**` を追記した。")
  changed = 1
}

# --- 操作: --rewrite ---------------------------------------------------------
# **なぜ在るか(2026-08-12)。**それまでの書き込み操作4つ(--add / --done / --note /
# --archive)は**どれも項目を短くできなかった** —— --note は積むだけ、--archive は
# `[x]` になるまで動かせない。結果、着手中の項目は更新行が積まれるほど太り、
# 実測で正典の冒頭が 10,538字(内 着手順が 9,113字 = 86%)まで育った。冒頭は
# **10,000字を超えると無言で切り詰められる**(#70460 / #84021)ので、後半は実際に
# 次のセッションへ届いていない。**縮める手段が1つも無い**のが直接の動機。
#
# やること:
#   1. 本文(項目行の概要 + ぶら下がる散文)を新しい本文へ差し替える
#   2. その項目の `> **YYYY-MM-DD 更新:**` を**すべて**消す(何を消したかは stderr へ全文)
#   3. --criteria があれば `→ 完了条件:` も差し替える。無ければ**現状のまま**
# 保つもの: チェック状態 `[ ]`/`[x]`、ID、**証拠行**、項目の並び順。
#
# ⚠️ **証拠行は消さない。**消すと `[x]` の項目が no-evidence 違反に化け、
#    「自分で書いた正典を自分の --lint が叱る」という 2026-08-08 と同型の壊れ方をする。
#    証拠は「何を確認したか」の記録で、本文が長いこととは無関係。
# ボツ案: 更新行を「最新の1本だけ残す」。残す基準が「新しい方が正しい」という
#    仮定に依存する(古い更新の方が重要なことは普通にある)。**全部消して、消したものを
#    その場で見せ、必要なら新しい本文へ書き手が畳み直す**方が、判断が人の側に残る。
# ボツ案: 移動先(log.md のどこへ移したか)の申告を必須にする。2026-08-09 の実測で
#    「毎セッション読まれる場所から移しても記録は失われない」ことが確認済み(履歴は
#    log.md と git にある)なので、書かせても行動を変えない義務が増えるだけ。
function do_rewrite(   k, i, m, parts, pair, ln, kd, ind, nb, bl, nn, np, notes, prose) {
  k = find_item(id)
  # 未知の ID は **unknown_id() = die() = exit 3**(何も書かずに落ちる)。
  # ⚠️ 仕様書には「exit 2」とあるが、**兄弟操作(--done / --note)に合わせて 3 にした。**
  #    このスクリプトの終了コードは 2 =「使い方の誤り(ファイルを読む前に分かる)」/
  #    3 =「対象の状態が合わない(未知の ID を含むと --help に明記)」で分けてある。
  #    ここだけ 2 にすると、`rc == 3 → ID が無い` で分岐している呼び出し側が
  #    --rewrite でだけ誤読する。**仕様の主眼(fail-closed で1バイトも書かない)は
  #    どちらでも満たす**ので、区別が壊れない側を採った。1行で戻せる判断なので、
  #    仕様どおり 2 にするなら unknown_id() を経由せず個別に落とすこと。
  if (k == 0) unknown_id()
  # 新しい行の字下げは既存の「→」行に合わせる。無ければ 6(`- [x] ` の幅 = --add が書く形)。
  # ⚠️ imind(継続行の最小字下げ)は**使わない** —— 更新行は 2 桁で書かれるので、
  #    更新行を持つ項目では imind が 2 に引きずられる。いま消そうとしている行の
  #    字下げに、これから書く行を合わせるのは筋が悪い。
  ind = (iaind[k] > 0 ? iaind[k] : 6)

  # --- 1) 継続行を種別ごとに仕分ける ---------------------------------------
  # 種別はパーサが出したもの(ikinds)。**ここで `^>` や `^→` を見てはいけない** ——
  # H-19 で1本化した「書式を解釈するのはパーサだけ」の線を跨ぐと、また答えが割れる。
  nn = 0; np = 0
  m = (ikinds[k] == "" ? 0 : split(ikinds[k], parts, " "))
  for (i = 1; i <= m; i++) {
    split(parts[i], pair, ":")
    ln = pair[1] + 0; kd = pair[2]
    if (kd == "u")      { del[ln] = 1; notes[++nn] = L[ln] }   # 更新行 → 全部消す
    else if (kd == "p") { del[ln] = 1; prose[++np] = L[ln] }   # 旧本文 → 差し替える
    else if (kd == "c") { if (setcrit) del[ln] = 1 }           # 完了条件 → --criteria のときだけ
    # kd == "e"(証拠行とその折り返し)は**触らない**。
  }
  # 項目の中の空行も落とす。本文を消した跡に空行だけが浮いて残ると、項目の切れ目に
  # 見えて読みにくいうえ、縮めるための操作なのに行が減らない。
  # ボツ案: 消した行に隣接する空行だけを選んで落とす。規則が「隣接とは何か」に依存して
  #   説明できなくなる割に、得られる差は空行1本ぶん(項目内の空行は元々ごく稀)。
  for (i = istart[k] + 1; i <= iend[k]; i++) if (blank(L[i])) del[i] = 1

  # --- 2) 項目行の概要を差し替える -----------------------------------------
  # `- [x] `ID`` までを**そのまま残す**ので、チェック状態も ID も定義上変わりようがない
  # (do_done のように状態文字を書き戻す形だと、保つ範囲が狭いぶん壊す余地が広い)。
  if (iscol[k] < 7 || index(substr(L[istart[k]], 1, iscol[k]), iid[k]) == 0)
    die("内部エラー: 項目行の「保つ範囲」に ID `" iid[k] "` が入っていない(" istart[k] " 行目)。**何も書いていない。**")
  prose[++np] = L[istart[k]]      # 旧本文の1行目 = 項目行。消えたものとして必ず見せる
  nb = split(ENVIRON["ND_BODY"], bl, "\n")
  L[istart[k]] = substr(L[istart[k]], 1, iscol[k]) " " bl[1]
  # 2行目以降は継続行として項目行の直後へ。sanitize_value が付けた 6 桁の字下げは
  # 剥がして ind へ揃え直す(項目ごとに実際の字下げが違いうるため)。
  for (i = 2; i <= nb; i++) add_ins(istart[k], sp(ind) lstrip(bl[i]))
  # 新しい完了条件は**本文の直後**に置く。--add が書く並び(概要 → 完了条件 → 証拠)と
  # 同じになり、証拠行より前に来る。
  # ボツ案: 元の `→ 完了条件:` の位置に差し込む。元の位置は項目ごとにばらつく(証拠行の
  #   後ろにあることすらある)ので、**差し替えるたびに並びが変わらない**方を選んだ。
  if (setcrit) add_ins(istart[k], sp(ind) "→ 完了条件: " ENVIRON["ND_CRITERIA"])

  # --- 3) 何を消したかを必ず見せる -----------------------------------------
  # **黙って消さない。**git に残るとはいえ、実行した本人がその場で見られないと
  # 「消えたことに気づくのが次のセッション」になる。stderr へ全文出す(W + D)。
  say("I", "`" id "` の本文を差し替えた" (setcrit ? "(完了条件も差し替えた)" : "(完了条件は元のまま)") "。")
  if (np > 0) {
    say("W", "置き換えた本文 " np " 行(消えた内容。必要なら log.md へ移すこと):")
    # 項目行を prose の最後に積んであるので、表示だけ先頭へ回して元の並びに戻す。
    say("D", prose[np])
    for (i = 1; i < np; i++) say("D", prose[i])
  }
  if (nn > 0) {
    say("W", "削除した更新行 " nn " 本(`> **… 更新:**`。git には残るが、いま消えたものをここに出す):")
    for (i = 1; i <= nn; i++) say("D", notes[i])
    # **同じ行を機械用にもう一度積む。**U = bash 側の log.md 照合(check_notes_against_log)が
    # 読む控えで、emit_report は表示しない(N / C と同じ「機械用の値」の扱い)。
    # ボツ案: D レコードを再利用する。D には**置き換えた本文**も混ざっているので、
    #   照合したい行(更新行だけ)を選り分けられない —— 選り分けようとすると bash 側で
    #   `^>` を見ることになり、**書式を解釈するのはパーサだけ**という H-19 の線を跨ぐ。
    #   種別 u はパーサが下した判定なので、その結果をそのまま持ち出すのが筋。
    for (i = 1; i <= nn; i++) say("U", notes[i])
  }
  # `[x]` で証拠行が無い項目は、`(移行: 証拠なし)` の免除が**本文の中にあった**可能性が
  # 高い。本文ごと差し替えると免除も消え、次の --lint が no-evidence で鳴る ——
  # 鳴ってから原因を探すのは高くつくので、その場で言っておく(止めはしない)。
  if (istat[k] == "x" && !ihas_evi[k])
    say("W", "`" id "` は `[x]` だが証拠行が無い —— 本文に `(移行: 証拠なし)` が入っていた場合、差し替えで免除も消えるので `--lint` が no-evidence で鳴る。`--done " id " --evidence \"何を確認したか\"` で証拠を足すか、新しい本文へ免除を書き直すこと。")
  changed = 1
}

# --- 操作: --archive --------------------------------------------------------
# ✅ の日付は証拠行の先頭にある YYYY-MM-DD(パーサが出す iedate)を使う。無ければ今日。
# 「今日」を無条件に使うと、3日前に閉じた項目が今日閉じたことになって記録が嘘になる。
# ⚠️ 旧実装はここで証拠行を自前で ltrim → `→` 剥がし → 日付マッチしていた。
#    **証拠行の書式の2つ目の実装**なので、抽出ごとパーサへ移した(H-19)。
function evi_date(k) { return (iedate[k] != "" ? iedate[k] : today) }

function move_item(k, dst,   i, sh, ln, dt, s) {
  dt = evi_date(k)
  # 完了記録の書式は既存の実物に合わせる: `- ~~`ID` 概要~~ ✅ YYYY-MM-DD`。
  # チェックボックス形式のまま降ろすのはボツ —— 完了記録は「## 着手順」の外なので
  # 読み側のパーサが見ない。`[x]` のまま置くと、書式だけ機械可読で誰も読まない行になる。
  s = "`" iid[k] "` " isum[k]
  # ⚠️ **手書き様式との衝突を避ける。** 移行前の実物には
  # `- [x] `IOS-3` ~~概要~~ ✅(2026-08-04)` のように、打ち消し線と ✅ を**項目行の中に
  # 手で書いた**ものが在る(docs/ios-skills/next-directions.md で実際に踏んだ)。
  # そこへ機械的に `~~ … ~~` を被せると打ち消し線が入れ子になって markdown が壊れ、
  # ✅ も2つ並ぶ。既にあるなら足さない —— 人が書いた形の方を正とする。
  # ボツ案: 既存の `~~` と `✅…` を剥がして正規化する。項目の文言そのものを削ることになり、
  # 「移すだけ」という約束を超える(どこまでが装飾でどこからが本文かは機械には判らない)。
  if (index(s, "~~") == 0) s = "~~" s "~~"
  if (index(s, "✅") == 0) s = s " ✅ " dt
  add_ins(dst, "- " s)
  # 継続行は**相対構造を保ったまま**平行移動する(最小字下げが 2 になるように)。
  # 一律に 2 桁へ潰すのはボツ: 「→」行とその折り返しの深さの差が消え、
  # 読み側の折り返し判定と食い違う形になる(完了記録は読まれないが、
  # 人が着手順へ戻したくなったときに壊れた形が残るのは避ける)。
  # 最小字下げもパーサが出した値(imind)を使う。0 = 継続行が1本も無い(下のループも回らない)。
  sh = (imind[k] == 0 ? 0 : imind[k] - 2)
  for (i = istart[k] + 1; i <= iend[k]; i++) {
    if (blank(L[i])) { add_ins(dst, ""); continue }
    ln = L[i]
    # mind は最小字下げなので、どの行も先頭 sh 文字は必ず空白。安全に落とせる。
    if (sh > 0) ln = substr(ln, sh + 1)
    else if (sh < 0) ln = sp(-sh) ln
    add_ins(dst, ln)
  }
  for (i = istart[k]; i <= iend[k]; i++) del[i] = 1
  # 直後の空行は、直上も空行のときだけ一緒に落とす(空行が2本続くのを作らない)。
  if (iend[k] + 1 < se && blank(L[iend[k] + 1]) && istart[k] > 1 && blank(L[istart[k] - 1]))
    del[iend[k] + 1] = 1
  say("M", "`" iid[k] "` " isum[k] " → `## 完了記録`(✅ " dt ")")
}

function do_archive(   k, i, nm, dst, has_entry) {
  nm = 0
  for (k = 1; k <= ni; k++) {
    if (istat[k] != "x") continue
    # **証拠行を持たない `[x]` は移さない。** 移すと「検証されていない完了」が
    # 恒久記録に残り、後から見分けられなくなる(--lint の no-evidence も、
    # 着手順から出た瞬間に検査対象外になって黙る)。
    if (!ihas_evi[k]) {
      say("W", "`" iid[k] "` は `[x]` だが証拠行が無い —— **移さない**。先に `--done " iid[k] " --evidence \"何を確認したか\"` で証拠を足すこと(移行免除の `(移行: 証拠なし)` も証拠ではないので同じ扱い)。")
      continue
    }
    nm++; mv[nm] = k
  }
  say("C", nm)
  if (nm == 0) {
    say("I", "移す対象は0件(証拠行を持つ `[x]` 項目が無い)。何もしていない。")
    changed = 0
    return
  }
  if (ds == 0) {
    # 置き場が無ければ作る。位置は session-head-end マーカーの直後 ——
    # 完了記録は「頭」ではなくカタログ側に属する(閉じた項目を毎セッション注入する理由は無い)。
    if (mk == 0)
      die("`## 完了記録` 節が無く、作る位置(`<!-- session-head-end` マーカー)も無い —— **何も書いていない。** 先に `## 完了記録` 節を作るか、マーカーを入れること(/harness:doctor が配る雛形が正)。")
    dst = mk
    add_ins(dst, "")
    add_ins(dst, "## 完了記録(着手順から降ろしたもの)")
    add_ins(dst, "")
    add_ins(dst, "冒頭は予算制なので、完了した項目はここへ降ろす。**ID は再利用しない**(log.md から参照されるため)。")
    add_ins(dst, "")
    # 過去形にしない —— このメッセージは dry-run でも出る(まだ1バイトも書いていない)。
    say("I", "`## 完了記録` 節が無いので、session-head-end マーカーの直後に新設する。")
  } else {
    # 既存の節へは**末尾に追記**する。先頭へ挿すのはボツ —— 追記なら git 差分が
    # 「+N -M(着手順から消えた分)」で読め、既存行の位置が動かない(log.md の
    # append-only と同じ理屈。索引だけが新しい順で、本文は時系列)。
    # 追記位置(dat = 節の中の最後の非空行)と既存エントリの有無(dhas)は**パーサが出す** ——
    # ここで `/^- /` を書くと、それが「箇条書きとは何か」の N 個目の実装になる。
    dst = dat; has_entry = dhas
    # 既存エントリがあれば詰めて並べる(実物の完了記録は項目間に空行が無い)。
    # 導入散文しか無い節にいきなりぶら下げると段落と箇条書きが繋がるので、そのときだけ空行。
    if (!has_entry) add_ins(dst, "")
  }
  for (i = 1; i <= nm; i++) move_item(mv[i], dst)
  # 全部降ろすと「着手順」節が空になる。**それ自体は正しい状態**(やることが無い)だが、
  # 読み側の --lint は項目0件を `not-migrated`(旧書式のまま未移行)と診断して落ちる ——
  # 空にした本人には的外れな診断で、原因を探して時間を溶かす。
  # ここで先に言っておく。**止めはしない**(強制は最小・検知は最大。空にする自由は残す)。
  # ボツ案: 最後の1件は移さない。「やることが無い」を表現できなくなるうえ、
  # なぜ1件だけ残るのかが利用者から見て説明できない。
  if (ni - nm == 0)
    say("W", "これで「## 着手順」の項目が0件になる —— **--lint は0件を `not-migrated`(未移行)と診断して非0で落ちる**(空にしたこと自体は異常ではないが、検査器から見ると書式ドリフトと区別が付かない)。次の項目を `--add` で足すこと。")
  changed = 1
}

# --- 出力 -------------------------------------------------------------------
# 削除と挿入を1回のループで反映する。**元の行はそのまま印字する**(整形し直さない)——
# 節の外はもちろん、節の中でも触っていない行が1バイトでも変わると、
# 「着手順だけを書き換えた」という約束が検証できなくなる(git diff で見えなくなる)。
function emit(   i, j) {
  for (i = 1; i <= n; i++) {
    if (!del[i]) print L[i]
    for (j = 1; j <= insn[i]; j++) print ins[i, j]
  }
}

