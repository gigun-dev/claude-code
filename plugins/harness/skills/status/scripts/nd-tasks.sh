# 「N 文字目で切る」は書けない —— このスクリプトが相手にする awk はバイト単位なので、
# 日本語の途中で切れて表示も照合も壊れる。句点・読点・空白で切れば必ず文字境界になる。
# 長さは **compact() した後**(実際に照合する形)で測る。⚠️ ここを「切る前の生の長さ」で
# 測っていた初版は、`排他ロックを mkdir ` で切ると生 24B・潰すと 23B になり、**log.md に
# 全文が在るのに「キーが短い」側へ落ちた**(実測して直した)。切る基準と短さの基準が
# 別々の物差しだと、こういう1バイトのズレが黙って別のバケツへ運ぶ。
# ボツ案: 更新行の全文をキーにする。**厳しすぎる** —— 末尾を1字だけ変えて移しても
#   「見つからない」になり、鳴りっぱなしの検知器は読まれなくなる(原則5)。
#   倒れる先は安全側でも、鳴りすぎれば検知器は死ぬ。
function make_key(body,   cut, key) {
  cut = 0
  while (1) {
    cut = next_break(body, cut)
    if (cut == 0) return body                      # もう区切りが無い = 本文まるごと
    key = substr(body, 1, cut)
    if (length(compact(key)) >= minb) return key   # 十分に特徴的になったら打ち切り
  }
}

