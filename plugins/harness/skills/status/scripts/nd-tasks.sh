# 字下げも折り返しも変わるのが普通で、そこで一致しなくなるのは「移していない」ではなく
# 「整形が違う」でしかない。改行も落とすので、90桁で折り返された log.md の行を
# またぐ文字列にも当たる。
function compact(s) {
  gsub(/\*\*/, "", s)
  gsub(/[ \t\r\n]/, "", s)
  gsub(/(　)+/, "", s)   # 全角空白。⚠️ 多バイトは [] に入れず、量化子はグループへ掛ける
  return s
}

# 更新行から「本文」を取り出す(`> **YYYY-MM-DD 更新:**` の接頭辞と強調記法を落とす)。
# ⚠️ ここで `>` を見ているのは**書式の解釈ではない** —— どの行が更新行かはパーサが決めて
#    U レコードとして渡ってきており、この関数は渡された行から**照合に使わない飾り**を
#    落としているだけ。接頭辞が無い形(手書きの `> 2026-08-12 更新: …` など)でも落とせる
#    範囲だけ落として先へ進む。fail-closed にする理由は無い —— 落とし損ねるとキーが
#    長くなるだけで、倒れる先は「見つからない」= 安全側。
function strip_note(s,   t) {
  t = s
  sub(/^[ \t]+/, "", t)
  while (t ~ /^>/) sub(/^>[ \t]*/, "", t)          # `> >` の入れ子も剥がす
  sub(/^(\*\*)?[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9][ \t]*更新(:|：)(\*\*)?[ \t]*/, "", t)
  gsub(/\*\*/, "", t)
  sub(/^[ \t]+/, "", t); sub(/[ \t]+$/, "", t)
  return t
}

# after より後ろで最初に現れる区切りの位置(= その手前までの長さ)。0 = もう無い。
function next_break(s, after,   i, off, idx, p, best) {
  best = 0
  for (i = 1; i <= nd; i++) {
    off = after; p = 0
    while (1) {
      idx = index(substr(s, off + 1), delim[i])
      if (idx == 0) { p = 0; break }
      p = off + idx - 1
      if (p > after) break
      off = off + idx + length(delim[i]) - 1
    }
    if (p > 0 && (best == 0 || p < best)) best = p
  }
  return best
}

