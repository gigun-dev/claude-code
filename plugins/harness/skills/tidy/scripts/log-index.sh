nskipped=0

# 1ファイルの1ブロックを処理する。マーカーを探し、中身を生成し、差し替える(or 鮮度を見る)。
# 2ブロックを同じ手順で回すための関数化 —— 日付索引と却下索引で挙動が割れると、
# 「片方だけ静かに更新されない」という一番気づきにくい壊れ方をする。
# ⚠️ ブロックごとに毎回 grep で行番号を取り直す。先に片方を差し替えると後ろのブロックの
#    行番号がずれるため、最初にまとめて数えてはいけない(冪等性が壊れる)。
process_block() {
  local f="$1" mode="$2" ms="$3" me="$4" label="$5"
  local s e rc body new dst

  # --only で絞られていたら何もしない(黙って返す。「対象外」は異常ではない)。
  if [ -n "$ONLY" ] && [ "$ONLY" != "$mode" ]; then return 0; fi

  # マーカーは**行頭アンカー**で探す。散文中で "log-index start" に言及しただけで
  # 索引の境界が動くのを防ぐ(session-start.sh がマーカーを行頭で探すのと同じ理由)。
  s=$(grep -n -m1 -F -x "$ms" "$f" | cut -d: -f1 || true)
  e=$(grep -n -m1 -F -x "$me" "$f" | cut -d: -f1 || true)

  if [ -z "$s" ] || [ -z "$e" ]; then
    if [ ${#EXPLICIT[@]} -gt 0 ]; then
      # 明示指定 = 「このファイルに索引を入れろ」という意思表示。黙って何もしない選択肢は無い。
      echo "✗ $f: ${label}のマーカーが無い。テンプレートのマーカーを入れてから再実行すること:" >&2
      echo "    $ms" >&2
      echo "    $me" >&2
      echo "  (位置は先頭の位置づけブロックの直後。雛形は plugins/harness/skills/init/assets/log.md)" >&2
      status=1
    else
      # 自動探索 = 「索引を持つと宣言した log.md」を回るモード。未導入は既知の状態なので
      # 終了コードは動かさない。ただし**名指しで出す**(黙って対象から消えるのが一番まずい)。
      echo "⚠️ $f: ${label}のマーカーが無いので飛ばした(未導入)。導入するならテンプレートの" >&2
      echo "   $ms / $me を先頭へ入れて再実行すること。" >&2
      nskipped=$((nskipped + 1))
    fi
    return 0
  fi
  if [ "$s" -ge "$e" ]; then
    echo "✗ $f: ${label}のマーカーの順序が逆(start=$s 行 / end=$e 行)。start を先に置くこと。" >&2
    status=1
    return 0
  fi

  body="$tmp/body"
  rc=0
  perl "$GEN" "$mode" "$f" > "$body" || rc=$?
  if [ "$rc" -eq 3 ]; then
    # fail-closed。ここを「索引が空でよい」と解釈すると、書式が変わった日に索引が
    # 黙って消える。0件の原因は2つに割れる(未移行 / ドリフト)が、どちらも
    # **人が本文を見て直すしかない**ので同じ赤にする。
    echo "✗ $f: 行頭 '## ' の見出しが1本も無い —— 索引を作れない。" >&2
    echo "  見出しは '## YYYY-MM-DD 一行タイトル' 形式にすること(日付だけの見出しにしない)。" >&2
    echo "  **見出しが無いことを「索引が空でよい」と解釈してはいけない** —— 書式が変わった" >&2
    echo "  可能性がある。旧書式(箇条書きだけのログ)なら見出しへの移行が要る。" >&2
    status=1
    return 0
  elif [ "$rc" -ne 0 ]; then
    echo "✗ $f: ${label}の生成に失敗した(perl 終了コード $rc)。" >&2
    status=1
    return 0
  fi

  # マーカー行そのものは温存し、間だけ差し替える。前後は sed で無加工にコピーする
  # (テキスト処理を通すと末尾改行や特殊文字で本文が変質しうるので、加工は一切しない)。
  new="$tmp/new"
  { sed -n "1,${s}p" "$f"; cat "$body"; sed -n "${e},\$p" "$f"; } > "$new"

  if cmp -s "$f" "$new"; then
    # ここも `[ … ] && echo` の1行形にしない(上と同じ set -e の罠。CHECK=0 のとき
    # ループ本体の最後の非0になる)。
    if [ "$CHECK" -eq 1 ]; then echo "✓ $f: ${label}は最新"; fi
    return 0
  fi

  if [ "$CHECK" -eq 1 ]; then
    echo "✗ $f: ${label}が古い。log-index.sh を実行して差分に含めること" >&2
    status=1
    return 0
  fi

  # 同じディレクトリへ書いてから mv する。**mv は同一ファイルシステム内なら atomic** で、
  # 途中で落ちても log.md が切り詰められた状態にはならない。追記専用アーカイブを
  # 半分だけ書き潰すのは復旧不能な事故なので、ここは atomicity を優先する
  # (代償としてファイルのパーミッションは umask 由来に戻るが、.md なので実害なし)。
  dst="$f.log-index.tmp.$$"
  cp "$new" "$dst"
  mv "$dst" "$f"
  echo "✓ $f: ${label}を更新した($(grep -c '^- ' "$body" || true) 件)"
  nupdated=$((nupdated + 1))
  return 0
}

for f in "${files[@]}"; do
  process_block "$f" index    "$MARK_START"   "$MARK_END"   "日付索引"
  process_block "$f" rejected "$MARK_R_START" "$MARK_R_END" "却下索引"
done

if [ "$nskipped" -gt 0 ]; then
  echo "(索引マーカーを持たないブロックを ${nskipped} 件飛ばした。上の ⚠️ を参照)" >&2
fi
# 「0件更新」も明示する。冪等なスクリプトは黙って何もしないのが正常系なので、
# **何も起きなかったこと自体を出力する**(無出力だと「動いたのか?」が分からない)。
if [ "$CHECK" -eq 0 ] && [ "$nupdated" -eq 0 ] && [ "$status" -eq 0 ]; then
  echo "索引は全て最新(${#files[@]} ファイル)。更新なし。"
fi
exit "$status"
