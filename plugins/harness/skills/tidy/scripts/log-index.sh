#!/usr/bin/env bash
# harness-template v0.13.0 (配布元: gigun-dev/claude-code plugins/harness)
#   — log.md の索引(先頭・新しいものが上)を生成する。**マーカー間だけ**を書き換える。
#   生成するブロックは2つ: **日付索引**(`## ` 見出し)と**却下索引**(`R-n` の付いた行)。
#
# 設計意図(2026-08-07):
#   log.md は追記専用アーカイブで、放っておくと 1,000 行を軽く超える。実測(2026-08-07、
#   配布済み5リポジトリ):
#       caldav        1,424行 146,565B  見出し 50本(append-only 実測 +1424 -0)
#       swift-mcp-app 1,251行 117,004B  見出し 81本
#       tdr-concierge   473行  43,926B  見出し 19本
#   この規模で「どこに何があるか」に答えるには、**全文をロードせずに拾い読みできる入口**が
#   要る。それが索引。手で維持すると必ず腐る(追記のたびに2箇所書く規律は人にもモデルにも
#   守れない)ので、機械が書く。
#
#   **索引は新しいものが上 / 本文は追記専用なので末尾が最新。**この非対称は意図的で、
#   「今どうなってる?」に索引だけで答えられるようにするためのもの。
#   ボツ案: 本文自体を新しい順に積む(= 先頭に挿入する)。追記のたびに既存行の位置が動き、
#   git 差分が「+1424 -0」の追記専用でなくなる(caldav の実測がまさにこの形)。
#   append-only の性質は、後から本当に書き換えていないことを差分で検証できる唯一の担保
#   なので手放さない。
#
#   **却下索引を分けている理由**(2026-08-07 追加): 却下の記録は log.md に既に高い質で
#   書けていた。無かったのは **ID と索引**だけ —— Rust RFC 3137 が6年前に closed した PR の
#   個別コメントを今でも引けるのは URL が安定 ID だったからで、**ID の無い段落は引けない**。
#   日付索引に混ぜないのは、却下を引く動機(「その案は前に検討したか?」)が日付ではなく
#   **判断そのもの**から始まるため。日付索引に埋めると、日付を知らない人には到達できない。
#   ボツ案: ADR ディレクトリを作る / `status:` フィールドを持つ。どちらも却下済み ——
#   置き場は既にあり、状態は git が表現している(MADR 本家ですら 19 本中 3 本しか
#   `status:` を運用していない)。**足りないのは保存ではなく到達性**。
#
#   **fail-closed。** 「マーカーが無い(明示指定時)」「`## ` 見出しが0本」はどちらも非0で
#   落とす。0件を「索引が空でよい」と解釈すると、見出し書式が変わった日に索引が黙って消えて、
#   誰も気づかないまま拾い読みの入口だけが失われる —— nd-tasks.sh が empty-section で
#   潰したのと同じ死に方(この repo では鮮度検査が2リポジトリで黙って死んだ前科がある)。
#   **ただし却下索引だけは0件でも落とさない。**却下記録が無いのは「壊れた」ではなく
#   「まだ何も却下していない」= 正常な状態でありうる(見出しと違い、書式変更で0件になる
#   経路が無い —— `R-n` はバッククォート囲みの ID で、書式が変わりようがない)。
#
#   **ただし自動探索でマーカーが無いファイルは「未導入」として飛ばす(警告つき・終了コードは
#   動かさない)。**根拠は nd-tasks.sh の --all と同じ理屈: fail-closed が本当に効いてほしいのは
#   「**前は読めていたものが読めなくなった**」= ドリフト。「まだ索引を入れていない」は既知の
#   状態であって異常ではない。ここを一律に赤にすると、旧書式の log.md を1本でも持つ
#   リポジトリでは tidy が毎回赤になり、**赤の意味が消えて本物のドリフトが埋もれる**。
#   飛ばすときは必ずファイル名を名指しで stderr に出す(黙って消えることはない)。
#   明示指定(引数)は「そのファイルに索引を入れろ」という意思表示なので、そちらは厳密に落とす。
#
#   **書き換えるのはマーカー間だけ。**本文には一切触らない —— 追記専用の規律を、それを
#   支援するはずの道具が破ったら本末転倒になる。差分が「索引ブロックだけ」であることは
#   git diff で毎回確認できる。
#
#   アンカーの生成は GitHub(jch/html-pipeline の TableOfContentsFilter)の規則に合わせる:
#       小文字化 → \p{Word}・ハイフン・空白**以外**を除去 → 空白をハイフン → 重複に -1, -2
#   日本語・全角括弧・丸数字が実際に入る(caldav の `## 2026-07-13(続き)②-c …`)ため、
#   ここを自前の近似で済ませるとリンクが**静かに壊れる**(踏むまで分からない種類のバグ)。
#   実装は perl —— Ruby の \p{Word} と perl の \w は同じ定義(Alpha + Mark + Nd +
#   Connector_Punctuation)。ボツ案: awk / sed。macOS の awk はブラケット式をバイト単位で
#   解釈するので、全角括弧や丸数字だけを落とす表現が書けない(nd-tasks.sh のパーサに同じ
#   注意書きがある)。python3 もボツ —— Python の \w は str.isalnum() 基準で **No カテゴリ
#   (丸数字 ②)まで拾ってしまい**、GitHub と結果が食い違う。
set -euo pipefail

# 索引ブロックの境界。**この4行は書き換えない**(中身だけ差し替える)。
# HTML コメントなので描画には出ない = 読み手には索引本体だけが見える。
MARK_START='<!-- log-index start -->'
MARK_END='<!-- log-index end -->'
MARK_R_START='<!-- rejected-index start -->'
MARK_R_END='<!-- rejected-index end -->'

usage() {
  cat <<'EOF'
使い方: log-index.sh [--check] [<log.md> ...]

log.md の先頭にある2つの索引ブロックを、本文から再生成する。
**マーカー間以外は1バイトも書き換えない。**

  <!-- log-index start -->      〜 <!-- log-index end -->        日付索引(`## ` 見出し)
  <!-- rejected-index start --> 〜 <!-- rejected-index end -->   却下索引(`R-n` の行)

走査対象:
  既定        ${CLAUDE_PROJECT_DIR:-.} 配下の docs/log.md と docs/*/log.md
              (単一プロダクト型 / コンポーネント別の両対応)。
              索引マーカーを持たないものは「未導入」として飛ばす(名指しで警告は出す)。
              2つのブロックは独立に判定する(片方だけ導入していてもよい)。
  <path> ...  明示したファイルだけを処理する。**マーカーが無ければ落とす**
              (「入れろ」と指定された以上、黙って何もしないのは禁止)。

オプション:
  --check     書き換えない。どちらかの索引が最新でなければ非0で終了する
              (CI / pre-push / tidy 用)。
  --only <index|rejected>
              片方のブロックだけを対象にする。**用途は1つだけ** —— 却下索引をまだ
              入れていない配布済みリポジトリで、日付索引の鮮度検査を生かしたまま
              「却下索引が無い」を赤にしないため(tidy.sh がこの形で呼ぶ)。
              新しいブロックを足すたびに既存の配布先が一斉に赤くなると、
              **赤の意味が消えて本物のドリフトが埋もれる**。
  -h, --help  これ。

日付索引の中身:
  行頭 `## ` の見出しだけを拾い、**新しいものが上**(ファイル内の出現順の逆)に並べる。
  本文は追記専用なので末尾が最新 —— 索引だけ逆順なのは意図的で、「今どうなってる?」に
  索引だけで答えられるようにするため。
  フェンス付きコードブロックの中の `## ` は見出しではないので拾わない
  (拾うと GitHub に存在しないアンカーへのリンクを作ってしまう)。

却下索引の中身:
  バッククォート囲みの `R-n`(却下・見送りの安定 ID)を含む行を拾い、**採番の新しい順**に
  並べる。リンク先はその行が属する `## ` 見出しのアンカー。
  本文側の書式は次の形(ID とラベルを既存の記録に前置するだけ。文章は書き換えない):

      - `R-1` **却下: <一行タイトル>** — <既存の理由の文章をそのまま>

  表示テキストは「ID の後ろから最初の em ダッシュ `—` まで」。`—` が無ければ行末まで。
  採番は**時系列で追記専用**(欠番も再利用もしない)。同じ ID が複数行にあるときは
  最初の1行だけを採り、残りは警告する(散文からの参照を定義と取り違えないため)。
  **却下0件はエラーにしない** —— ブロックを空にして正常終了する。
  却下記録には判断の根拠(一次資料 URL / issue 番号 / 実測値)を添える。ただし
  **過去分は遡らない**(後付けのルールを遡及させると、達成できずに規約ごと死ぬ。
  PEP は Rejected 131 本中 `Resolution:` を持つのが 42 本だけ)。

終了コード:
  0  最新(--check)/ 生成・更新した(既定)
  1  索引が古い(--check)/ `## ` 見出しが0本 / 明示指定したファイルにマーカーが無い
  2  使い方の誤り / 対象が1件も無い
EOF
}

CHECK=0
ONLY=''
EXPLICIT=()
while [ $# -gt 0 ]; do
  case "$1" in
    --check) CHECK=1; shift ;;
    --only)
      [ $# -ge 2 ] || { echo "--only には index か rejected が要る" >&2; exit 2; }
      case "$2" in
        index|rejected) ONLY="$2" ;;
        *) echo "--only の値が不正: $2(index か rejected)" >&2; exit 2 ;;
      esac
      shift 2 ;;
    -h|--help) usage; exit 0 ;;
    -*) echo "不明な引数: $1" >&2; usage >&2; exit 2 ;;
    *) EXPLICIT+=("$1"); shift ;;
  esac
done

# perl は macOS の base system に入っており(5.34)、Linux でも git の依存で実質必ずある。
# それでも**無いときに黙って素通りさせない** —— 索引が更新されないまま「成功」を返すのが
# 一番まずい(検知器が静かに死ぬ、この repo が最も嫌う失敗の形)。
command -v perl >/dev/null 2>&1 || {
  echo "✗ perl が無い。索引のアンカー生成は GitHub の Unicode 規則に合わせる必要があり、" >&2
  echo "  awk/sed のバイト単位のブラケット式では代替できない。perl を入れてから再実行すること。" >&2
  exit 2
}

tmp=$(mktemp -d "${TMPDIR:-/tmp}/log-index.XXXXXX")
trap 'rm -rf "$tmp"' EXIT

# --- 索引本体の生成器(perl) ---------------------------------------------------
# `log-index.pl <index|rejected> <file>` で、標準出力へ「マーカー間に入る中身」だけを出す。
# index モードで見出しが0本なら exit 3(呼び出し側が fail-closed のメッセージに翻訳する)。
# rejected モードは0件でも exit 0(却下が無いのは正常)。
#
# 両モードで**同じ走査ループ**を使う。アンカーの重複サフィックス(-1 / -2)は文書全体の
# 見出しの通し番号で決まるので、モードごとに別実装を書くと**却下索引のリンクだけが静かに
# ずれる**(H1/H3 を数え漏らすのと同じ事故)。
#
# ⚠️ プログラムは一時ファイルへ書いて perl に食わせる。`PROG=$(cat <<'PL' …)` の形にしては
#    いけない —— bash 3.2(macOS 標準)は $( ) の中では引用符付きヒアドキュメントの中身まで
#    走査し、本文のバッククォートをコマンド置換の開始と誤認して構文エラーになる
#    (nd-tasks.sh のパーサで実際に踏んだ)。ここもフェンス検出で ``` を書くので必ず出る。
GEN="$tmp/log-index.pl"
cat > "$GEN" <<'PL'
use strict;
use warnings;
# ⚠️ このプログラム自身のリテラル(下の日本語の注記行)も UTF-8 で書かれている。
#    use utf8 が無いと**リテラルだけがバイト列のまま**扱われ、:encoding(UTF-8) の出力層で
#    二重エンコードされて文字化けする(最初の実装で実際に化けた)。
use utf8;

my $mode = shift or die "usage: log-index.pl <index|rejected> <file>\n";
my $file = shift or die "usage: log-index.pl <index|rejected> <file>\n";
die "unknown mode: $mode\n" unless $mode eq 'index' || $mode eq 'rejected';
open(my $fh, '<:encoding(UTF-8)', $file) or die "open failed: $file: $!\n";

my @entries;    # レベル2見出しだけ [表示テキスト, アンカー]
my @rej;        # 却下記録 [番号, 表示テキスト, 見出しテキスト, アンカー]
my %seen;       # 却下 ID の重複検出
my @dups;
my %used;       # アンカーの出現回数。GitHub の -1 / -2 サフィックスはこれで決まる
my $fchar = ''; # 開いているフェンスの記号(''=フェンスの外)
my $flen  = 0;  # 開いたときの長さ。閉じるには同じ記号で同じ長さ以上が要る
my $incom = 0;  # 複数行の HTML コメント(<!-- … -->)の中か
my $inblk = 0;  # 生成済み索引ブロックの中か
my ($cur_text, $cur_anchor) = ('', '');   # 直近の `## ` 見出し(却下索引のリンク先)

while (my $line = <$fh>) {
    chomp $line;
    $line =~ s/\r$//;

    # --- 自分が生成したブロックの中は読まない -----------------------------------
    # ⚠️ **冪等性の要**。却下索引の中身は `- `R-3` 見送り: … → [見出し](#…)` の形をしており、
    #    ここを本文と一緒に走査すると **2回目の実行で自分の出力を却下記録として拾い直す**
    #    (ID が重複して索引が膨らむ)。日付索引の側も同様に読み飛ばす —— 現状は
    #    `- [text](#anchor)` なので見出しにはならないが、書式を変えた瞬間に壊れる依存を
    #    残さない。マーカー行の判定は**行頭アンカーの完全一致**で行う(散文中で
    #    "rejected-index start" に言及しただけで境界が動くのを防ぐ。sh 側の grep -F -x と同じ規則)。
    if ($line eq '<!-- log-index start -->' || $line eq '<!-- rejected-index start -->') {
        $inblk = 1;
        next;
    }
    if ($line eq '<!-- log-index end -->' || $line eq '<!-- rejected-index end -->') {
        $inblk = 0;
        next;
    }
    next if $inblk;

    # --- 複数行の HTML コメント --------------------------------------------------
    # コメントアウトされた見出しは描画されない = GitHub はアンカーを作らない。拾うと
    # **存在しないアンカーへのリンク**になる。実在の例: vuejs-translations/docs-ja の
    # README は `<!--\n## 貢献する\n-->` で見出しごと一時的に伏せており、素朴な実装だと
    # ここで壊れたリンクを2本作った(GitHub の描画結果と突き合わせて発見)。
    # ⚠️ フェンス判定より**前**に置く。コメントは自分の中のフェンス記号を無効化するため。
    if ($incom) {
        $incom = 0 if $line =~ /-->/;
        next;
    }

    # --- フェンス付きコードブロック --------------------------------------------
    # ログには実際にシェルやログの貼り付けが入り、その中の `## …`(コメント行など)を
    # 見出しと誤認すると **GitHub に存在しないアンカーへのリンク**を作ってしまう。
    # 壊れたリンクは踏むまで気づけないので、ここは黙って落とすより検出する側に倒す。
    # 却下 ID も同じ —— 書式の説明としてコードブロックに貼った見本の `R-n` を拾うと、
    # **存在しない却下記録**が索引に載る(この repo の assets/log.md がまさに見本を持つ)。
    if ($fchar eq '') {
        if ($line =~ /^ {0,3}(`{3,}|~{3,})/) {
            $fchar = substr($1, 0, 1);
            $flen  = length($1);
            next;
        }
    } else {
        # 閉じフェンスは「同じ記号・同じ長さ以上・後ろは空白のみ」(CommonMark)。
        if ($line =~ /^ {0,3}(\Q$fchar\E{$flen,})[ \t]*$/) { $fchar = ''; }
        next;   # フェンスの中身は見出しになり得ない
    }

    # --- 行内で完結する HTML コメント --------------------------------------------
    # 索引のマーカー行自身は上で処理済み。ここに来るのは本文中のコメント。
    # 除去した結果が空行になるものは見出しにならない。閉じずに開いたままのものは、
    # 次の行以降がコメントの中。
    $line =~ s/<!--.*?-->//g;
    if ($line =~ /<!--/) { $incom = 1; next; }

    # --- 却下記録の ID ----------------------------------------------------------
    # 拾うのは**バッククォート囲みの `R-n`**。着手順の `H-n` と同じ記法にしてあるので、
    # 散文中の "R-1" のような裸の文字列は拾わない(誤検出の主要因を記法で潰している)。
    if ($mode eq 'rejected' && $line =~ /`R-(\d+)`\s*(.*)$/) {
        my ($n, $rest) = ($1, $2);
        # 表示テキストは「ID の後ろから最初の em ダッシュまで」。本文側の書式
        # `**却下: タイトル** — 理由` の**理由を索引に持ち込まない**ため。
        # `—` が無い記録(理由が別行にある / タイトルだけ)は行末まで採る。
        $rest =~ s/\s*—.*$//;
        $rest =~ s/\*\*//g;      # 強調記法は索引に要らない
        $rest =~ s/^\s+|\s+$//g;
        $rest =~ s/。$//;        # 見出し相当の短文に句点は付けない
        if ($seen{$n}++) {
            push @dups, $n;
        } else {
            push @rej, [ $n, $rest, $cur_text, $cur_anchor ];
        }
        # ⚠️ ここで next しない。ID を持つ行が見出しである運用に変わっても
        #    アンカーの通し番号がずれないようにする(下の見出し処理へ落とす)。
    }

    # --- ATX 見出し -------------------------------------------------------------
    # レベルは1〜6すべて拾う。**索引に出すのは `## ` だけだが、重複サフィックス
    # (-1 / -2)は GitHub が文書全体の見出しを通し番号で数えるため**、H1 や H3 も
    # 数え漏らすとアンカーがずれる。
    next unless $line =~ /^(\#{1,6})[ \t]+(.*?)[ \t]*$/;
    my $level = length($1);
    my $text  = $2;
    $text =~ s/[ \t]+\#+[ \t]*$//;   # 閉じ ATX(`## foo ##`)の後ろ側は見出しテキストではない

    # アンカーの素は「描画後のテキスト」。画像は本文テキストを持たない(<img> の .text は
    # 空)、リンクは表示テキストだけが残る。それ以外の強調・コード記号(* _ `)は、
    # 下の除去規則で結果的に同じ形になるので個別処理は要らない。
    # 既知の限界: `_強調_` は GitHub 側で <em> になりアンダースコアが消えるが、こちらは
    # \w に含まれるので残る。snake_case の識別子を壊さない方を優先して、あえて直さない。
    my $plain = $text;
    $plain =~ s/!\[[^\]]*\]\([^)]*\)//g;
    $plain =~ s/\[([^\]]*)\]\([^)]*\)/$1/g;
    # インライン HTML はタグごと消える(描画後のテキストには残らない)。実在の例:
    # yiisoft/yii2 の日本語ガイドは `## 見出し <span id="foo"></span>` の形で別名アンカーを
    # 埋めており、これを消さないと `-span-idfoospan` が付いた別物のアンカーになる。
    # `<` だけで `>` を伴わない書き方(`## a < b`)は GitHub 側でもタグにならないので、
    # 閉じ `>` を必須にして巻き込まない。
    $plain =~ s/<[^>]*>//g;

    # GitHub(jch/html-pipeline)の規則そのまま。順序も揃える —— 先に空白をハイフンに
    # してから除去すると、記号を挟んだ空白の扱いが変わって `--` の数がずれる。
    my $anchor = lc $plain;
    $anchor =~ s/[^\w\- ]//g;
    $anchor =~ s/ /-/g;

    my $n = $used{$anchor}++;
    $anchor .= "-$n" if $n;

    next unless $level == 2;
    ($cur_text, $cur_anchor) = ($text, $anchor);
    push @entries, [ $text, $anchor ];
}
