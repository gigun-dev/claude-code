# --- 対象の収集 ---------------------------------------------------------------
# 単一プロダクト型(docs/log.md)とコンポーネント別(docs/<comp>/log.md)の両対応。
# tidy.sh / nd-tasks.sh の探索と同じ形にしてある —— 片方だけ見るとこの repo のような
# マーケットプレイス型を取りこぼす。
files=()
if [ ${#EXPLICIT[@]} -gt 0 ]; then
  for f in "${EXPLICIT[@]}"; do
    [ -f "$f" ] || { echo "✗ ファイルが無い: $f" >&2; exit 2; }
    files+=("$f")
  done
else
  base=$(cd "${CLAUDE_PROJECT_DIR:-.}" && pwd)
  # `[ -f x ] && files+=(…)` の1行形は使わない —— グロブが1件も当たらないと、その行が
  # ループ本体(あるいはスクリプト)の最後の非0となり、set -e で**静かに途中終了する**。
  # 「対象が0件」は下できちんとメッセージにするので、ここで死んではいけない。
  if [ -f "$base/docs/log.md" ]; then files+=("$base/docs/log.md"); fi
  for f in "$base"/docs/*/log.md; do
    if [ -f "$f" ]; then files+=("$f"); fi
  done
  if [ ${#files[@]} -eq 0 ]; then
    echo "✗ ${base} に docs/log.md も docs/*/log.md も無い。" >&2
    echo "  log.md を持たないリポジトリなら不要(導入は /harness:init --with-log)。" >&2
    exit 2
  fi
fi

