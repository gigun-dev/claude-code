#!/usr/bin/env python3
"""Build one pinned npm plugin for every agent host from a single unpacked package.

nix/external-plugins.nix unpacks the tarball pinned in nix/npm-sources.json to
OUT/lib/NAME (left as published) and runs this script, which adds:

  OUT/bin/<server>-mcp               one executable per stdio MCP server in the
                                     package's .claude-plugin/plugin.json: the
                                     server's command with "node" replaced by
                                     --node and ${CLAUDE_PLUGIN_ROOT} by
                                     OUT/lib/NAME, plus the server's env and
                                     --env. Every host starts this command.
  OUT/share/agent-plugins/NAME/      the plugin for Claude Code (a skills-dir
                                     plugin) and Codex and other hosts that read
                                     Agent Plugins 1.0:
                                       plugin.json, mcp.json      Agent Plugins 1.0
                                       .claude-plugin/plugin.json Claude manifest
                                       skills/<skill>/            as published
  OUT/share/agy-plugins/NAME/        the agy variant: .antigravity-plugin/,
                                     mcp_config.json and skills/ split under
                                     agy's body limit (scripts/agy_wrap_plugin.py)

Why agy gets its own directory: agy reads skills from the same skills/ path
as Claude and Codex and has no setting for another one, so a split SKILL.md in
the shared directory would also be what Claude and Codex read. The directories
hold only manifests and skills; the package itself is OUT/lib/NAME once.

Every manifest names OUT/bin/<server>-mcp by absolute path, so no host resolves
node from PATH and none needs the consumer's environment (Codex clears it).

--servers and --skills are the names nix/npm-sources.json records for this
version. The build fails when the package declares others, so a release that
adds or renames one stops the weekly update instead of silently changing what
the consumer places.

usage: build_external_plugin.py OUT NAME --node PATH --shell PATH
                                [--env JSON] --servers JSON --skills JSON
       build_external_plugin.py --smoke EXECUTABLE...
"""

from __future__ import annotations

import argparse
import json
import shlex
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from agy_wrap_plugin import (  # noqa: E402
    WrapError,
    mcp_servers,
    probe,
    read_claude_manifest,
    skill_roots,
    split_skills,
    write_agy,
)
from generate_manifests import fmt_json  # noqa: E402

PLUGIN_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json"
MCP_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json"
# Top-level fields the Agent Plugins 1.0 plugin schema allows (additionalProperties: false).
AGENT_PLUGIN_FIELDS = ["name", "version", "description", "author", "homepage", "repository", "license", "keywords"]
AUTHOR_FIELDS = ["name", "email", "url"]
# Claude manifest fields carried over; the rest (icon, hooks, commands, ...)
# point at files the shared directory does not hold.
CLAUDE_FIELDS = AGENT_PLUGIN_FIELDS
ROOT_VAR = "${CLAUDE_PLUGIN_ROOT}"


def executable_name(server: str) -> str:
    return f"{server}-mcp"


def resolve(value: str, package: Path, what: str) -> str:
    out = value.replace(ROOT_VAR, str(package))
    if "${" in out:
        raise WrapError(f"{what}: {value!r} uses a variable this build does not expand")
    return out


def launcher(server: str, spec: dict, package: Path, node: str, shell: str, extra_env: dict[str, str]) -> str:
    """Shell text of OUT/bin/<server>-mcp for one stdio server."""
    if spec.get("type", "stdio") != "stdio" or "command" not in spec:
        raise WrapError(f"{server}: only stdio MCP servers are supported, got {spec!r}")
    unknown = set(spec) - {"type", "command", "args", "env"}
    if unknown:
        raise WrapError(f"{server}: MCP server fields this build drops: {sorted(unknown)}")
    command = node if spec["command"] == "node" else resolve(spec["command"], package, server)
    if not command.startswith("/"):
        # A bare command other than node would be looked up on the host's PATH,
        # which is what this executable exists to avoid.
        raise WrapError(f"{server}: command {spec['command']!r} is neither node nor inside the package")
    args = [resolve(a, package, server) for a in spec.get("args", [])]
    env = {k: resolve(v, package, server) for k, v in spec.get("env", {}).items()} | extra_env
    lines = [
        f"#!{shell}",
        "# Generated by scripts/build_external_plugin.py (nix/external-plugins.nix).",
        *(f"export {k}={shlex.quote(v)}" for k, v in sorted(env.items())),
        "exec " + " ".join(shlex.quote(p) for p in [command, *args]) + ' "$@"',
    ]
    return "\n".join(lines) + "\n"


def agent_plugin_manifest(claude: dict) -> dict:
    manifest: dict = {"$schema": PLUGIN_SCHEMA}
    for field in AGENT_PLUGIN_FIELDS:
        if field in claude:
            manifest[field] = claude[field]
    if isinstance(manifest.get("author"), dict):
        manifest["author"] = {k: v for k, v in manifest["author"].items() if k in AUTHOR_FIELDS}
    return manifest


def build(
    out: Path, name: str, node: str, shell: str, env: dict[str, dict[str, str]],
    expect_servers: list[str], expect_skills: list[str],
) -> list[str]:
    package = out / "lib" / name
    claude = read_claude_manifest(package)
    if claude["name"] != name:
        raise WrapError(f"{package}: .claude-plugin/plugin.json names {claude['name']!r}, pinned as {name!r}")
    servers = mcp_servers(package, claude)
    skills = {p.parent.name: p.parent for root in skill_roots(package, claude) for p in sorted(root.glob("*/SKILL.md"))}
    for what, found, expected in (("MCP servers", servers, expect_servers), ("skills", skills, expect_skills)):
        if sorted(found) != sorted(expected):
            raise WrapError(
                f"{name}: the package declares {what} {sorted(found)}, nix/npm-sources.json records "
                f"{sorted(expected)}; run scripts/update_external_plugins.py --write"
            )
    unknown = set(env) - set(servers)
    if unknown:
        raise WrapError(f"{name}: mcpEnv names servers the plugin does not have: {sorted(unknown)}")

    log = []
    bin_dir = out / "bin"
    bin_dir.mkdir(parents=True, exist_ok=True)
    executables = {}
    for server, spec in servers.items():
        path = bin_dir / executable_name(server)
        if path.exists():
            raise WrapError(f"{name}: {path.name} already exists; another plugin has a server named {server!r}")
        path.write_text(launcher(server, spec, package, node, shell, env.get(server, {})), encoding="utf-8")
        path.chmod(0o555)
        executables[server] = str(path)
        log.append(f"{name}: bin/{path.name}")

    shared = out / "share" / "agent-plugins" / name
    agy = out / "share" / "agy-plugins" / name
    for target in (shared, agy):
        for skill, source in skills.items():
            shutil.copytree(source, target / "skills" / skill)

    stdio = {s: {"command": exe} for s, exe in executables.items()}
    (shared / "plugin.json").write_text(fmt_json(agent_plugin_manifest(claude), compact=False), encoding="utf-8")
    if stdio:
        mcp = {"$schema": MCP_SCHEMA, "mcpServers": {s: {"type": "stdio"} | v for s, v in stdio.items()}}
        (shared / "mcp.json").write_text(fmt_json(mcp, compact=False), encoding="utf-8")
    claude_manifest = {f: claude[f] for f in CLAUDE_FIELDS if f in claude}
    if skills:
        claude_manifest["skills"] = "./skills"
    if stdio:
        claude_manifest["mcpServers"] = stdio
    (shared / ".claude-plugin").mkdir()
    (shared / ".claude-plugin" / "plugin.json").write_text(fmt_json(claude_manifest, compact=False), encoding="utf-8")
    log.append(f"{name}: share/agent-plugins/{name} (plugin.json, mcp.json, .claude-plugin/plugin.json)")

    log += [f"{line} (share/agy-plugins)" for line in write_agy(agy, claude, stdio, None, {})]
    log += split_skills(agy / "skills", name)
    return log


def smoke(executables: list[Path]) -> list[str]:
    # A bare environment: the executable must not need PATH, node or the
    # consumer's variables, because Codex starts MCP servers without them.
    home = Path.cwd()
    env = {"HOME": str(home), "PATH": "/usr/bin:/bin", "TMPDIR": str(home)}
    return [probe(exe.name, [str(exe)], str(home), env) for exe in executables]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("out", type=Path, nargs="?")
    ap.add_argument("name", nargs="?")
    ap.add_argument("--node")
    ap.add_argument("--shell")
    ap.add_argument("--env", default="{}", help='{"<server>": {"KEY": "value"}}')
    ap.add_argument("--servers", default="[]")
    ap.add_argument("--skills", default="[]")
    ap.add_argument("--smoke", nargs="+", type=Path, metavar="EXECUTABLE")
    args = ap.parse_args()
    if args.smoke:
        print("\n".join(smoke(args.smoke)))
        return 0
    if not (args.out and args.name and args.node and args.shell):
        ap.error("OUT, NAME, --node and --shell are required")
    try:
        for line in build(
            args.out, args.name, args.node, args.shell, json.loads(args.env),
            json.loads(args.servers), json.loads(args.skills),
        ):
            print(line)
    except WrapError as error:
        print(f"build_external_plugin: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
